def asn1_type_name(a_type):
    '''Return the type name with the proper casing as defined in ASN.1'''
    assert a_type.kind == 'ReferenceType'
    for typename in TYPES.keys():
        if typename.lower() == a_type.ReferencedTypeName.lower():
            return typename
    return f"ERROR: Type Not Found: {a_type.ReferencedTypeName}"


def type_name(a_type, use_prefix=True):
    '''Check the type kind and return a Rust usable type name.

    Maps ASN.1 types to the Rust types generated by asn1scc -Rust:
        ReferenceType  -> asn1Scc{Name}  (type alias or struct/enum name)
        BooleanType    -> bool
        Integer types  -> u64 (unsigned) or i64 (signed), based on range
        RealType       -> f64
        *StringType    -> [u8; N]  (OCTET STRING) or String (IA5String)
        EnumeratedType -> asn1Scc prefix (enum name resolved at call site)
    '''
    if a_type.kind == 'ReferenceType':
        if use_prefix:
            return ASN1SCC + a_type.ReferencedTypeName.replace('-', '_')
        else:
            return a_type.ReferencedTypeName.replace("-", "_")
    elif a_type.kind == 'BooleanType':
        return 'bool'
    elif a_type.kind.startswith('Integer32'):
        return 'i32'
    elif a_type.kind.startswith('IntegerU8'):
        return 'u8'
    elif a_type.kind.startswith('Integer'):
        if float(a_type.Min) >= 0:
            return 'u64'
        else:
            return 'i64'
    elif a_type.kind == 'RealType':
        return 'f64'
    elif a_type.kind.endswith('StringType'):
        # OctetString/BitString/IA5String are generated as structs with arr field
        return 'String'  # placeholder; actual handling in expression code
    elif a_type.kind == 'ChoiceEnumeratedType':
        return 'i64'
    elif a_type.kind == 'StateEnumeratedType':
        return ASN1SCC
    elif a_type.kind == 'EnumeratedType':
        return ASN1SCC if use_prefix else ''
    else:
        LOG.debug(str(traceback.format_exc()))
        raise NotImplementedError(f'Type name for {a_type.kind}')


def child_spelling(name, bty):
    '''Return the index in Children with the proper spelling (case, dash)'''
    for each in bty.Children:
        if name.lower().replace('_', '-') == each.lower():
            return each
    raise TypeError(f'Child not found: {name}')


def find_var(var):
    '''Return a variable from the scope, with proper case'''
    for visible_var in VARIABLES.keys():
        if var.lower() == visible_var.lower():
            return visible_var
    return None


def find_monitoring(mon):
    '''Return a monitoring from the scope, with proper case'''
    for visible_mon in MONITORS.keys():
        if mon.lower() == visible_mon.lower():
            return visible_mon
    return None


def is_local(var):
    '''Check if a variable is in the global context or in a local scope'''
    return var.lower() in (loc.lower() for loc in LOCAL_VAR.keys())


def default_pid():
    '''Return the default PID reference playing the role of "self".
    For process types, uses SELF_PID (set by the instance wrapper).
    Otherwise, uses asn1SccPID::asn1Sccenv (the environment PID).'''
    if PROCESS and getattr(PROCESS, 'process_type', False):
        return 'SELF_PID'
    return f'{ASN1SCC}PID::PID_env'


def default_dest_pid():
    '''Return the default DESTINATION PID of a message or a timer.

    When a model sends a message without an explicit TO, the message goes
    to the environment, i.e. it is multicast to every connected peer.
    This mirrors the Ada backend (Dest_PID : asn1sccPID := asn1sccEnv) and
    the C backend (default_pid): the middleware routing tables deliver a
    message only when its destination is the environment or the exact
    callee — any other value (in particular the sender's own SELF_PID)
    is silently dropped. Using SELF_PID here (as done previously) meant
    that the outputs of a process type were never delivered.
    '''
    return f'{ASN1SCC}PID::PID_env'


def ri_trait_name():
    '''Name of the generated RI trait for a process type.

    The instance wrapper implements this trait to plug its own RI
    implementations into the process type module, mirroring the
    "with procedure" generic formals of the Ada backend.
    '''
    return f'{PROCESS_NAME.capitalize()}Ri'


def ri_generic_sig(params=()):
    '''Return the generic formal-parameter part of a state machine function.

    For a process type, every function that (indirectly) calls a required
    interface is generic over the RI implementation:
        <Ri: Og_typeRi>(ri: &mut Ri, ze_param: &mut asn1SccMy_OctStr)
    For a standalone process the parameters are passed through unchanged.
    '''
    if GENERIC:
        rest = ''.join(f', {p}' for p in params)
        return f'<Ri: {ri_trait_name()}>(ri: &mut Ri{rest})'
    return f'({", ".join(params)})' if params else '()'


def ri_call_args(args=()):
    '''Return a call argument list, with "ri" first when generic.

    In generic mode the callee expects the RI implementation as its
    first argument (see ri_generic_sig).
    '''
    if GENERIC:
        return f'(ri, {", ".join(args)})' if args else '(ri)'
    return f'({", ".join(args)})' if args else '()'


def is_fpar(name):
    '''Check if a variable name is an fpar parameter (which is &mut in Rust)'''
    return name in FPAR_VARS or any(name.lower() == f.lower() for f in FPAR_VARS)


def canonical_timer_name(name):
    '''Return the declared spelling of a timer, matching case-insensitively.

    SDL is case-insensitive, but Rust is not: the set_/reset_ stubs are
    generated from process.timers (declared spelling), so a call site written
    in lowercase must be canonicalized (e.g. `mytimer` -> `myTimer`).
    '''
    timers = getattr(PROCESS, 'timers', None) or []
    for t in timers:
        tname = t if isinstance(t, str) else t.get('name', '')
        if tname.lower() == name.lower():
            return tname
    return name


def deref_fpar(var_str, name):
    '''Add * dereference prefix if the variable is an fpar parameter.

    Idempotent: a value already produced by _primary_variable for an fpar is
    `(*x)`, which must not be dereferenced a second time.
    '''
    s = var_str.lstrip()
    if is_fpar(name) and not (s.startswith('*') or s.startswith('(*')):
        return f'*{var_str}'
    return var_str


def path_type(path):
    '''Return the type of a path construct (a!b!c -> [a, b, c])'''
    if not path or not find_var(path[0]):
        return None, None
    declarations = dict(VARIABLES)
    declarations.update(MONITORS)
    vartype, _ = declarations[find_var(path[0])]
    asn1_name = vartype.ReferencedTypeName
    current = TYPES[asn1_name].type
    if len(path) > 1:
        for elem in path[1:]:
            current = find_basic_type(current)
            if 'procParams' in elem:
                continue
            if current.kind in ('SequenceType', 'ChoiceType'):
                elem_asn1 = elem.replace('_', '-').lower()
                type_idx, = (c for c in current.Children
                             if c.lower() == elem_asn1)
                current = current.Children[type_idx].type
            elif current.kind == 'SequenceOfType':
                current = current['type']
            elif current.kind.endswith('EnumeratedType'):
                pass
            else:
                raise TypeError('Expression ' + '.'.join(path) +
                                ' does not resolve')
        asn1_name = current.ReferencedTypeName
    kind = find_basic_type(current).kind.replace('-', '_')
    LOG.debug('[Rust Generator] Type of path ' + '!'.join(path) +
              ' is ' + asn1_name + ' (' + kind + ')')
    return kind, asn1_name.replace('-', '_')


def traceability(symbol):
    '''Return a list of strings with code-to-model traceability'''
    trace = [f'// {line}' for line in symbol.trace().split('\n')]
    if hasattr(symbol, 'req_ids') and symbol.req_ids:
        trace.append(f"// Requirement IDs: {', '.join(symbol.req_ids)}")
    if hasattr(symbol, 'comment') and symbol.comment:
        trace.extend(traceability(symbol.comment))
    return trace


def debug_trace(limit=2):
    '''Return a list of comments containing traceability to the code generator'''
    result = []
    for each in traceback.format_stack(limit=limit)[:-1]:
        formatted = each.replace('\n', ' ').split(',')
        function = formatted[2].strip().split(' ')[1]
        line_nb = formatted[1].strip()
        result.append(f'// !! stack: {function} {line_nb}')
    return result


def format_rust_code(stmts):
    '''Indent properly the Rust code.

    This is a simplified indenter that handles the common Rust constructs:
    { } increase/decrease, match arms, if/else, for/while, etc.
    '''
    indent = 0
    indent_pattern = '    '  # 4 spaces for Rust
    for line in stmts:
        stripped = line.strip()
        if not stripped:
            yield line
            continue
        # Count closing braces at start of line
        dec = 0
        inc = 0
        # Check for leading closing braces
        for ch in stripped:
            if ch == '}':
                dec += 1
            else:
                break
        # Check for trailing opening braces
        for ch in reversed(stripped):
            if ch == '{':
                inc += 1
            else:
                break
        indent = max(indent - dec, 0)
        yield indent_pattern * indent + stripped
        indent += inc
    # Nothing to yield after loop


