def is_numeric(string) -> bool:
    '''Return true if value is a number'''
    try:
        float(string)
    except ValueError:
        return False
    return True


def dataview_rust_names(process=None) -> Tuple[str, str]:
    '''Return (file_stem, module_name) for the ASN.1 dataview Rust modules.

    asn1scc names the generated Rust files after the *input ASN.1 file stem*,
    not after the ASN.1 module name:
      - ``datamodel.asn``   -> ``datamodel.rs`` / ``datamodelDef.rs``, whose
        internal import is ``use crate::datamodelDef::*;`` (module ``datamodel``).
      - ``dataview-uniq.asn`` -> ``dataview-uniq.rs`` / ``dataview-uniqDef.rs``,
        module ``dataview_uniq`` (a dash becomes an underscore in the Rust
        module identifier, while the file name keeps the dash).
    The C and Ada backends derive the same name from the ASN.1 file; Rust must
    too, otherwise a dataview not named ``dataview-uniq.asn`` (e.g. the test
    suite's ``datamodel.asn`` / ``dv.asn`` / ``dataview.asn``) fails to build.
    '''
    p = process if process is not None else PROCESS
    stem = 'dataview-uniq'
    try:
        files = list(getattr(getattr(p, 'DV', None), 'asn1Files', None) or [])
        if files:
            stem = os.path.splitext(os.path.basename(files[0]))[0]
    except TypeError:
        pass
    return stem, stem.replace('-', '_')


def external_ri_list(process, has_cs=False) -> List:
    '''Helper: create the list of required interfaces of a process type.

    Returns, in a fixed order, one entry per required interface that the
    process type needs from its environment — the exact set that the Ada
    backend passes as "with procedure" generic formals:
      - one `ri_0_{signal}` per output signal,
      - one `ri_0_{procedure}` per external (RI) procedure,
      - `set_{timer}` / `reset_{timer}` per timer,
      - `delete_instance` when a PID type is present (stop terminator),
      - `check_queue` when the model uses continuous signals.

    Each entry is a dict:
        'method':  trait method name (called as ri.<method> in generic code)
        'params':  list of (param_name, param_type) pairs
    '''
    result = []

    def add(method, params):
        # params: list of (param_name, param_type) — e.g. ('ze_rezult',
        # '&mut asn1SccMy_OctStr') or ('dest_pid', 'asn1SccPID')
        result.append({'method': method, 'params': params})

    for signal in process.output_signals:
        param_name = signal.get('param_name') or f'{signal["name"]}_param'
        params = []
        if 'type' in signal:
            params.append((param_name, f'&mut {type_name(signal["type"])}'))
        if 'PID' in TYPES:
            params.append(('dest_pid', f'{ASN1SCC}PID'))
        add(f'ri{SEPARATOR}{signal["name"]}', params)
    for proc in (proc for proc in process.procedures if proc.external):
        params = [(param['name'], f'&mut {type_name(param["type"])}')
                  for param in proc.fpar]
        if 'PID' in TYPES:
            params.append(('dest_pid', f'{ASN1SCC}PID'))
        add(f'ri{SEPARATOR}{proc.inputString}', params)
    for timer in process.timers:
        params = [('val', f'&mut {ASN1SCC}T_UInt32')]
        if 'PID' in TYPES:
            params.append(('dest_pid', f'{ASN1SCC}PID'))
        add(f'set_{timer}', params)
        params = []
        if 'PID' in TYPES:
            params.append(('dest_pid', f'{ASN1SCC}PID'))
        add(f'reset_{timer}', params)
    if has_cs and not MONITORS:
        add('check_queue', [('res', '&mut bool')])
    if 'PID' in TYPES:
        # The stop terminator of a process type deletes its own instance
        add('delete_instance', [('pid', f'{ASN1SCC}PID')])
    return result


def taste_instance_ri_wiring(inst_ri_list, ptype_node=None, has_cs=False):
    '''Classify the RI trait methods of a TASTE process type instance.

    In TASTE, the middleware glue (kazoo's invoke_ri-body template) provides
    C functions that implement the message-passing required interfaces of
    the instance:
        {instance}_RI_{signal}_To_PID(dest_pid, in_p1, ...)   message outputs
        {instance}_RI_get_sender(sender_pid, unused)         sender of last PI
        {instance}_check_queue(res)                          queue status
    Those are wired here so that the instance wrapper calls the glue
    directly, like the Ada backend does through kazoo's ri_adb template
    (the "with procedure" generic actuals of the instance package).

    The remaining entries (other external procedures, timers,
    delete_instance, get_last_error) have no unconditional glue: they stay
    user hooks, forwarded to the {instance}_ri.rs stub file.

    Returns a dict: method name -> glue function name, or None for the
    entries that must be forwarded to the user-editable stubs.
    '''
    wiring = {}
    inst_name = PROCESS_NAME.lower()
    output_names = set()
    if ptype_node is not None:
        output_names = {sig['name'].lower()
                        for sig in ptype_node.output_signals}
    for entry in inst_ri_list:
        method = entry['method']
        if method.startswith(f'ri{SEPARATOR}'):
            name = method[len(f'ri{SEPARATOR}'):]
            if name == 'get_sender':
                # Implicit service provided by the glue unconditionally
                wiring[method] = f'{inst_name}_RI_get_sender'
            elif name.lower() in output_names and 'PID' in TYPES:
                # Message output: one glue function per output signal.
                # The _To_PID variant exists only when the dataview
                # defines a PID type — without it there is no routing
                # and the entry stays a user hook.
                wiring[method] = f'{inst_name}_RI_{name}_To_PID'
            else:
                # Timer or other external procedure: no glue with this
                # name — leave it as a user hook
                wiring[method] = None
        elif method == 'check_queue':
            wiring[method] = f'{inst_name}_check_queue'
        else:
            wiring[method] = None
    return wiring


