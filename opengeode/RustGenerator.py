@generate.register(ogAST.Decision)
def _decision(dec, branch_to=None, sep='if ', last='}', exitcalls=[], **kwargs):
    '''Generate code for a decision (if/else or match)'''
    code, local_decl = [], []
    else_code = []

    if dec.kind == 'any':
        code.extend(traceability(dec))
        nb = len(dec.answers)
        code.append(f'match gen_{nb}_init() {{')
        for idx, a in enumerate(dec.answers):
            code.append(f'{idx + 1} => {{')
            if not branch_to:
                if a.transition:
                    stmt, tr_decl = generate(a.transition)
                else:
                    stmt, tr_decl = ['{}'], []
                code.extend(stmt)
                local_decl.extend(tr_decl)
            else:
                for exit in exitcalls:
                    code.append(exit)
                code.append(f'tr_id = {branch_to};')
            code.append('}')
        code.append('_ => {}')
        code.append('}')
        return code, local_decl

    elif dec.kind == 'informal_text':
        code.append(f'// Informal decision ignored: {dec.inputString}')
        return code, local_decl

    elif dec.kind == 'alternative':
        if dec.alternative is not None:
            return generate(dec.alternative)
        else:
            return code, local_decl

    # Normal decision
    question_type = dec.question.exprType
    actual_type = type_name(question_type)
    question_basic = find_basic_type(question_type).kind
    basic = question_basic in (
        'IntegerType', 'Integer32Type', 'IntegerU8Type',
        'BooleanType', 'RealType', 'EnumeratedType', 'ChoiceEnumeratedType')

    if not basic:
        local_decl.append(f'let mut tmp{dec.tmpVar}: {actual_type} = Default::default();')

    q_stmts, q_str, q_decl = expression(dec.question, readonly=1)
    # The question may be a procedure formal parameter, received as &mut:
    # dereference it so comparisons and copies see the value.
    if isinstance(dec.question, ogAST.PrimVariable):
        q_name = dec.question.value[0].split('.')[0]
        q_str = deref_fpar(q_str, q_name)
    code.extend(traceability(dec))
    local_decl.extend(q_decl)
    if q_stmts:
        # Wrap question statements in a block to avoid for...else syntax issues
        code.append('{')
        code.extend(q_stmts)
        code.append('}')
    else:
        code.extend(q_stmts)

    if not basic:
        code.append(f'tmp{dec.tmpVar} = {q_str};')

    previous_ans = ''
    for idx, a in enumerate(dec.answers):
        code.extend(traceability(a))

        sub_sep = ''
        exp = ''
        ans_pre_stmts = []
        for element in a.answers:
            ans_kind = element['kind']
            ans_content = element['content']
            qbty = find_basic_type(question_type)

            if ans_kind in ('open_range', 'constant'):
                op, constant = ans_content
                ans_stmts, ans_str, ans_decl = expression(constant, readonly=1)
                # Collect answer statements to emit inside the if body
                ans_pre_stmts.extend(ans_stmts)
                local_decl.extend(ans_decl)

                # Rust uses == and != instead of = and /=
                rust_op = '==' if op.operand == '=' else '!=' if op.operand == '/=' else op.operand

                if not basic:
                    if op in (ogAST.ExprEq, ogAST.ExprNeq):
                        if isinstance(constant, (ogAST.PrimSequenceOf,
                                                 ogAST.PrimStringLiteral)):
                            if qbty.kind == 'IA5StringType':
                                # Use question_type (the Asn1Type with ReferencedTypeName) instead of qbty
                                ans_str = array_content(constant, ans_str, question_type)
                            else:
                                ans_str = array_content(constant, ans_str, question_type)
                        # Wrap ans_str in parentheses if it's a struct literal
                        if ans_str and ' { ' in ans_str and ans_str.startswith(ASN1SCC):
                            expPart = f'{actual_type}_Equal(&tmp{dec.tmpVar}, &({ans_str}))'
                        else:
                            expPart = f'{actual_type}_Equal(&tmp{dec.tmpVar}, &{ans_str})'
                        if op == ogAST.ExprNeq:
                            exp += f'{sub_sep}!{expPart}'
                        else:
                            exp += f'{sub_sep}{expPart}'
                    else:
                        rust_op = op.operand
                        exp += f'{sub_sep}tmp{dec.tmpVar} {rust_op} {ans_str}'
                else:
                    if isinstance(constant, (ogAST.PrimBitStringLiteral,
                                             ogAST.PrimOctetStringLiteral)):
                        ans_str = str(constant.numeric_value)

                    if actual_type != 'bool':
                        if question_basic.startswith('Integer'):
                            # Cast BOTH sides to the question's type: the parsed
                            # question (e.g. num(enum) -> i64) and the answer
                            # literal may otherwise have different widths
                            # (Rust has no implicit integer promotion).
                            exp += (f'{sub_sep}({q_str} as {actual_type}) {rust_op} '
                                    f'({ans_str} as {actual_type})')
                        else:
                            exp += f'{sub_sep}({q_str}) {rust_op} {ans_str}'
                    elif ans_str == 'true' and previous_ans != 'false':
                        exp += f'{sub_sep}({q_str})'
                    elif ans_str == 'false' and previous_ans != 'true':
                        exp += f'{sub_sep}!({q_str})'
                    else:
                        exp = 'ELSEONLY'
                previous_ans = ans_str

            elif ans_kind == 'closed_range':
                cl0_stmts, cl0_str, cl0_decl = expression(ans_content[0], readonly=1)
                cl1_stmts, cl1_str, cl1_decl = expression(ans_content[1], readonly=1)
                code.extend(cl0_stmts)
                local_decl.extend(cl0_decl)
                code.extend(cl1_stmts)
                local_decl.extend(cl1_decl)
                exp += f'{sub_sep}({q_str} >= {cl0_str} && {q_str} <= {cl1_str})'

            elif ans_kind == 'informal_text':
                continue
            elif ans_kind == 'else':
                if a.transition:
                    else_code, else_decl = generate(a.transition)
                else:
                    else_code, else_decl = ['{}'], []
                local_decl.extend(else_decl)

            sub_sep = " || "

        if exp:
            if exp == 'ELSEONLY':
                code.append('else {')
            else:
                code.append(sep + exp + ' {')
            # Emit answer pre-statements inside the if body, BEFORE the transition code
            # This runs after the condition is checked, but the not-expression
            # is evaluated in the condition itself (tmp was already computed)
            code.extend(ans_pre_stmts)
            if not branch_to:
                if a.transition:
                    stmt, tr_decl = generate(a.transition)
                else:
                    stmt, tr_decl = ['{}'], []
                code.extend(stmt)
                local_decl.extend(tr_decl)
            else:
                for exit in exitcalls:
                    code.append(exit)
                code.append(f'tr_id = {branch_to};')
            # If this was an ELSEONLY (else answer), reset sep to prevent
            # the try block from generating another else { }
            if exp == 'ELSEONLY':
                sep = 'if '
            else:
                sep = 'else if '
            code.append('}')

    try:
        if sep != 'if ':
            code.append('else {')
            if else_code:
                code.extend(else_code)
            elif not branch_to and not IN_PROCEDURE:
                # Empty else block — return Branch_End to satisfy the
                # Branches return type (process level only: a procedure
                # returns (), so no such value may be produced).
                code.append('return Branches::Branch_End;')
            code.append('}')
        else:
            code.extend(else_code)
    except:
        pass

    return code, local_decl


@generate.register(ogAST.Label)
def _label(lab, **kwargs):
    '''Label: return branch (process) or continue (procedure)'''
    try:
        context = lab.path[-1]
        is_procedure = 'PROCEDURE' in context
    except Exception:
        is_procedure = False
    if not is_procedure:
        return [f'return Branches::{lab.inputString}; // Join to label'], []
    else:
        # Rust doesn't have goto; labels in procedures are handled via
        # floating label functions (same approach as process-level)
        return [f'// Label {lab.inputString} (handled via floating label)'], []


@generate.register(ogAST.Transition)
def _transition(tr, **kwargs):
    '''Generate the code for a transition'''
    code, local_decl = [], []
    empty_transition = all(isinstance(act, ogAST.TaskInformalText)
                           for act in tr.actions)
    for action in tr.actions:
        stmt, local_var = generate(action)
        code.extend(stmt)
        local_decl.extend(local_var)
        if isinstance(action, ogAST.Label):
            break
    else:
        if tr.terminator:
            ns = tr.terminator.inputString.strip()
            empty_transition = False
            code.extend(traceability(tr.terminator))
            if tr.terminator.kind == 'next_state':
                history = ns in ('-', '-*')
                if tr.terminator.next_is_aggregation and not history:
                    code.append(f'// Entering state aggregation {tr.terminator.inputString}')
                    if not NO_CONTEXT:
                        if not tr.terminator.substate:
                            code.append(f'{LPREFIX}.state = {generate_state_name(tr.terminator.inputString)};')
                        else:
                            code.append(f'{LPREFIX}.{tr.terminator.substate}{SEPARATOR}state = {generate_state_name(tr.terminator.inputString)};')
                    code.append(f'{tr.terminator.next_id}();')
                    code.append('return Branches::Continuous_Signals;')
                elif not history:
                    if tr.terminator.next_id == -1:
                        if not NO_CONTEXT:
                            if not tr.terminator.substate:
                                code.append(f'{LPREFIX}.state = {generate_state_name(tr.terminator.inputString)};')
                            else:
                                code.append(f'{LPREFIX}.{tr.terminator.substate}{SEPARATOR}state = {generate_state_name(tr.terminator.inputString)};')
                        code.append('return Branches::Continuous_Signals;')
                    else:
                        if tr.terminator.instance_of:
                            code.append(f'// Instance {tr.terminator.inputString}')
                            if not NO_CONTEXT:
                                code.append(f'{LPREFIX}.state_instance = {generate_state_name(tr.terminator.inputString)};')
                        code.append(f'return Branches::{tr.terminator.next_id};')
                else:
                    # History: nextstate - or -*
                    code.append('// Go back to previous state')
                    if ns != '-*' and any(next_id
                           for next_id in tr.terminator.candidate_id.keys()
                           if next_id != -1):
                        code.append(f'match {LPREFIX}.state {{')
                        done = []
                        for nid, sta in tr.terminator.candidate_id.items():
                            if nid != -1:
                                if tr.terminator.next_is_aggregation:
                                    statement = f'{nid}();' if ns != '-*' else 'return Branches::Continuous_Signals;'
                                else:
                                    statement = f'return Branches::{nid},'
                                states_prefix = [generate_state_name(s) for s in sta]
                                done.extend(s.split(SEPARATOR)[0] for s in sta)
                                joined = ' | '.join(states_prefix)
                                if joined:
                                    code.append(f'{joined} => {statement}')
                        code.append('_ => return Branches::Continuous_Signals,')
                        code.append('}')
                    else:
                        code.append('// No change of state')
                        if not MONITORS:
                            code.append('return Branches::Continuous_Signals;')
                        else:
                            code.append('return Branches::Branch_End;')
            elif tr.terminator.kind == 'join':
                kind = tr.terminator.path[-1].split()[0] if tr.terminator.path else 'PROCESS'
                if kind == 'PROCEDURE':
                    if PROC_LABEL_NAMES:
                        code.append(f'__next = "{tr.terminator.inputString}";')
                        code.append('continue;')
                    else:
                        code.append(f'// Join to {tr.terminator.inputString}')
                else:
                    code.append(f'return Branches::{tr.terminator.inputString};')
            elif tr.terminator.kind == 'stop':
                if 'PID' in TYPES:
                    if GENERIC:
                        # Process type: delete the instance via the RI
                        # (generic formal "with procedure Delete_Instance")
                        code.append(f'ri.delete_instance(SELF_PID);')
                    else:
                        code.append(f'delete_instance(self);')
                    code.append(f'unsafe {{ {LPREFIX} = Default::default(); }}')
                    code.append(f'{LPREFIX}.init_done = false;')
                code.append('return Branches::Continuous_Signals;')
            elif tr.terminator.kind == 'return':
                string = ''
                aggregate = False
                if tr.terminator.substate:
                    aggregate = True
                    # Within a state aggregation, a return means that ONE
                    # parallel substate finished. Set it to the "finished"
                    # pseudo-state; only when ALL siblings are finished may
                    # the aggregation exit procedure run. The return value
                    # (branch/Continuous_Signals) is therefore emitted
                    # inside the if/else on the sibling condition.
                    code.append(f'{LPREFIX}.{tr.terminator.substate}{SEPARATOR}state = {generate_state_name("state" + SEPARATOR + "end")};')
                    conds = [f'{LPREFIX}.{sib}{SEPARATOR}state == {generate_state_name("state" + SEPARATOR + "end")}'
                             for sib in tr.terminator.siblings
                             if sib.lower() != tr.terminator.substate.lower()]
                    if conds:
                        code.append(f'if {" && ".join(conds)} {{')
                    else:
                        # No unfinished sibling: aggregation exit runs now
                        aggregate = False

                if tr.terminator.next_id == -1:
                    retexp = tr.terminator.return_expr
                    if retexp:
                        stmts, string, local = expression(retexp, readonly=1)
                        if isinstance(tr.terminator.context, ogAST.Procedure):
                            basic = find_basic_type(tr.terminator.context.return_type)
                            if isinstance(retexp, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
                                if basic.kind == 'IA5StringType':
                                    string = ia5string_raw(retexp)
                                elif basic.kind.startswith('Integer'):
                                    string = str(retexp.numeric_value)
                                else:
                                    string = array_content(retexp, string, basic)
                        code.extend(stmts)
                        local_decl.extend(local)
                    if not tr.possible_states and not string:
                        kind = tr.terminator.path[-1].split()[0] \
                            if tr.terminator.path else 'PROCESS'
                        if kind == 'PROCEDURE':
                            code.append('return;')
                        else:
                            code.append('return Branches::Continuous_Signals;')
                    else:
                        if string:
                            code.append(f'return {string};')
                        else:
                            code.append('return Branches::Continuous_Signals;')
                else:
                    if not MONITORS:
                        last_path = tr.terminator.path[-1].split()
                        if last_path[0] == 'STATE':
                            if len(tr.terminator.next_trans) == 1:
                                ret_branch = getattr(
                                    tr.terminator.next_trans[0], 'branch_label', None)
                                if ret_branch:
                                    code.append(f'return Branches::{ret_branch};')
                                else:
                                    code.append('return Branches::Branch_End;')
                            else:
                                code.append(f'return match {LPREFIX}.state_instance {{')
                                for nt in tr.terminator.next_trans:
                                    statename = nt.possible_states[0]
                                    next_branch = getattr(nt, 'branch_label', 'Continuous_Signals')
                                    code.append(f'{generate_state_name(statename)} => Branches::{next_branch},')
                                code.append('_ => Branches::Continuous_Signals,')
                                code.append('};')
                        else:
                            code.append('return Branches::Continuous_Signals;')
                    else:
                        code.append('return Branches::Branch_End;')
                if aggregate:
                    # close the "all siblings finished" if-block, then the
                    # else branch runs when at least one sibling is still
                    # active: stay in the aggregation (Continuous_Signals)
                    code.append('}')
                    code.append('else {')
                    if not MONITORS:
                        code.append('return Branches::Continuous_Signals;')
                    else:
                        code.append('return Branches::Branch_End;')
                    code.append('}')
    if empty_transition:
        code.append('// (empty transition)')
    return code, local_decl


@generate.register(ogAST.Floating_label)
def _floating_label(label, **kwargs):
    '''Generate the code for a floating label'''
    code = []
    if label.path:
        kind = label.path[-1].split()[0]
    else:
        kind = 'PROCESS'

    code.extend(traceability(label))
    if kind != 'PROCEDURE':
        # Function returning Branches
        code.append(
            f'unsafe fn branch_{label.inputString}{ri_generic_sig()} -> Branches {{')
    if label.transition:
        code_trans, local_trans = generate(label.transition)
        if local_trans:
            for decl in set(local_trans):
                code.append(decl)
        code.extend(code_trans)
        if kind != 'PROCEDURE':
            code.append('}')
            code.append('')
    else:
        if kind != 'PROCEDURE':
            code.append('Branches::Continuous_Signals')
            code.append('}')
            code.append('')
    return code, []


@generate.register(ogAST.Procedure)
def _inner_procedure(proc, is_rpc=True, **kwargs):
    '''Generate the code for a procedure'''
    code = []
    local_decl = []

    global IN_PROCEDURE
    outer_scope = dict(VARIABLES)
    local_scope = dict(LOCAL_VAR)
    local_fpar = set(FPAR_VARS)
    outer_in_procedure = IN_PROCEDURE
    IN_PROCEDURE = True
    VARIABLES.update(proc.variables)
    LOCAL_VAR.update(proc.variables)
    for var in proc.fpar:
        elem = {var['name']: (var['type'], None)}
        VARIABLES.update(elem)
        LOCAL_VAR.update(elem)
        FPAR_VARS.add(var['name'])

    pi_header = procedure_header(proc)
    # Rust does not need forward declarations (function ordering doesn't matter)

    if proc.external:
        # External procedure: declare as extern with full signature
        params = []
        for fpar in proc.fpar:
            typename = type_name(fpar['type'])
            params.append(f'{fpar.get("name")}: &mut {typename}')
        param_str = ', '.join(params) if params else ''
        ret_str = f' -> {type_name(proc.return_type)}' if proc.return_type else ''
        local_decl.append(f'extern "C" {{ fn {proc.inputString}({param_str}){ret_str}; }}')
    else:
        # Generate inner procedures recursively
        for inner_proc in proc.content.inner_procedures:
            inner_code, inner_local = generate(inner_proc)
            local_decl.extend(inner_local)
            code.extend(inner_code)

        code.extend(traceability(proc))
        code.append(f'{pi_header} {{')

        # Local variables
        for var_name, (var_type, def_value) in proc.variables.items():
            typename = type_name(var_type)
            if def_value:
                # Expression must be a ground expression, i.e. must not
                # require temporary variable to store computed result
                dst, dstr, dlocal = expression(def_value, readonly=1)
                varbty = find_basic_type(var_type)
                if varbty.kind.startswith('Integer') and \
                        isinstance(def_value, (ogAST.PrimOctetStringLiteral,
                                               ogAST.PrimBitStringLiteral)):
                    dstr = str(def_value.numeric_value)
                elif varbty.kind in ('SequenceOfType', 'OctetStringType', 'BitStringType'):
                    dstr = array_content(def_value, dstr, varbty)
                elif varbty.kind == 'IA5StringType':
                    dstr = ia5string_raw(def_value)
                assert not dst and not dlocal, 'Ground expression error'
                code.append(f'let mut {var_name}: {typename} = {dstr};')
            else:
                code.append(f'let mut {var_name}: {typename} = Default::default();')

        Helper.inner_labels_to_floating(proc)

        # Check if the top level process has continuous signals. This is also
        # taken into account to decide if there is need to call the _Transition
        # procedure.
        process_has_cs = any(PROCESS.cs_mapping.values())

        has_transition = any(proc.inputString.lower() == k.lower()
                             for k in PROCESS.input_mapping.keys()) or process_has_cs
        if proc.exported and proc.content.start is not None and is_rpc and has_transition:
            # Exported procedure end calling the corresponding transition
            # procedure that allows user to change state after RPC call
            # We need to update all the transitions of the procedure
            # (including floating labels) that contain a return statement
            # and add the call to the _Transition procedure before the return
            trans_with_return = []
            for each in chain([proc.content.start.transition],
                    (lab.transition for lab in proc.content.floating_labels)):
                def rec_transition(trans):
                    if trans.terminator:
                        if trans.terminator.kind == 'return':
                            trans_with_return.append(trans)
                    elif isinstance(trans.actions[-1], ogAST.Decision):
                        # There is no terminator, so the transition may finish
                        # with a DECISION, we must check it recursively
                        for answer in trans.actions[-1].answers:
                            rec_transition(answer.transition)
                rec_transition(each)

            for trans in trans_with_return:
                call_trans = ogAST.ProcedureCall()
                call_trans.inputString = f'{proc.inputString}_Transition'
                trans_proc = f'{proc.inputString}_Transition'
                call_trans.output = [{'outputName': trans_proc,
                                     'params': [], 'tmpVars': []}]
                trans.actions.append(call_trans)

        # Check if procedure has floating labels (from inner labels extraction)
        has_labels = len(proc.content.floating_labels) > 0

        if has_labels:
            # Generate label dispatch loop
            label_names = [l.inputString for l in proc.content.floating_labels]
            PROC_LABEL_NAMES[:] = label_names
            code.append('let mut __next: &str = "__start";')
            code.append('loop {')
            code.append('    match __next {')
            code.append('        "__start" => {')

        # Start transition
        if proc.content.start and proc.content.start.transition:
            tr_code, tr_decl = generate(proc.content.start.transition)
        else:
            tr_code, tr_decl = ['// empty procedure'], []
        for d in set(tr_decl):
            code.append(d)
        code.extend(tr_code)

        # Floating labels
        if has_labels:
            code.append('        }')
            for label in proc.content.floating_labels:
                code.append(f'        "{label.inputString}" => {{')
                code_label, label_decl = generate(label)
                code.extend(code_label)
                code.append('        }')
            code.append('        _ => { return; }')
            code.append('    }')
            code.append('}')
            PROC_LABEL_NAMES[:] = []
        else:
            # No labels: generate floating labels inline (process-level style)
            for label in proc.content.floating_labels:
                code_label, label_decl = generate(label)
                code.extend(code_label)

        code.append('}')

    code.append('')

    # Restore scope
    VARIABLES.clear()
    VARIABLES.update(outer_scope)
    LOCAL_VAR.clear()
    LOCAL_VAR.update(local_scope)
    FPAR_VARS.clear()
    FPAR_VARS.update(local_fpar)
    IN_PROCEDURE = outer_in_procedure

    return code, local_decl


def procedure_header(proc):
    '''Build the Rust prototype of a procedure'''
    ret_type = type_name(proc.return_type) if proc.return_type else None
    sep = f'p{SEPARATOR}' if not proc.exported else ''
    proc_name = proc.inputString
    # Exported procedures need to be pub(crate) for instance wrappers to access
    vis = 'pub(crate) ' if proc.exported else ''
    params = []
    for fpar in proc.fpar:
        typename = type_name(fpar['type'])
        # Rust: in params are &mut, out params are &mut
        params.append(f'{fpar.get("name")}: &mut {typename}')
    if GENERIC and not proc.external:
        # In a process type, inner/exported procedures can call required
        # interfaces: they are generic over the RI implementation too.
        if ret_type:
            pi_header = (f'{vis}unsafe fn {sep}{proc_name}'
                         f'{ri_generic_sig(params)} -> {ret_type}')
        else:
            pi_header = f'{vis}unsafe fn {sep}{proc_name}{ri_generic_sig(params)}'
    else:
        params_str = ', '.join(params) if params else ''
        if ret_type:
            pi_header = f'{vis}unsafe fn {sep}{proc_name}({params_str}) -> {ret_type}'
        else:
            pi_header = f'{vis}unsafe fn {sep}{proc_name}({params_str})'
    return pi_header


