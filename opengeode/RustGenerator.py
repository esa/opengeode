@expression.register(ogAST.PrimConditional)
def _conditional(cond, **kwargs):
    stmts = []
    local_decl = []
    basic_cond = find_basic_type(cond.exprType)
    actual_type = type_name(cond.exprType)

    if hasattr(cond, 'expected_type') and cond.expected_type:
        cond.value['then'].expected_type = cond.expected_type
        cond.value['else'].expected_type = cond.expected_type

    if_stmts, if_str, if_local = expression(cond.value['if'], readonly=1)
    then_stmts, then_str, then_local = expression(cond.value['then'], readonly=1)
    else_stmts, else_str, else_local = expression(cond.value['else'], readonly=1)

    stmts.extend(if_stmts)
    local_decl.extend(if_local)

    # Rust ternary: if cond { then } else { else }
    if actual_type == 'String' or basic_cond.kind == 'IA5StringType':
        rust_string = f'(if {if_str} {{ {then_str} }} else {{ {else_str} }})'
    else:
        local_decl.append(f'let mut tmp{cond.value["tmpVar"]}: {actual_type} = Default::default();')
        stmts.extend(then_stmts)
        stmts.extend(else_stmts)
        stmts.append(f'if {if_str} {{')
        stmts.append(f'    tmp{cond.value["tmpVar"]} = {then_str};')
        stmts.append(f'}} else {{')
        stmts.append(f'    tmp{cond.value["tmpVar"]} = {else_str};')
        stmts.append(f'}}')
        rust_string = f'tmp{cond.value["tmpVar"]}'

    local_decl.extend(then_local)
    local_decl.extend(else_local)
    return stmts, str(rust_string), local_decl


@expression.register(ogAST.PrimSequence)
def _sequence(seq, **kwargs):
    stmts, local_decl = [], []
    type_name_str = type_name(seq.exprType)
    type_children = find_basic_type(seq.exprType).Children

    fields = []
    for elem, value in seq.value.items():
        delem = elem.replace('_', '-')
        for each in type_children:
            if each.lower() == delem.lower():
                elem_spec = type_children[each]
                break
        elem_bty = find_basic_type(elem_spec.type)
        value_stmts, value_str, local_var = expression(value, readonly=1)

        if isinstance(value, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
            if elem_bty.kind.startswith('Integer'):
                value_str = str(value.numeric_value)
            elif elem_bty.kind in ('IA5StringType', 'StringType'):
                value_str = array_content(value, value_str, elem_spec.type)
            else:
                value_str = array_content(value, value_str, elem_spec.type)
            # Wrap in parentheses if it's a struct literal (to disambiguate from blocks)
            if value_str and ' { ' in value_str and value_str.startswith(ASN1SCC):
                value_str = f'({value_str})'

        fields.append(f'{elem}: {value_str}')
        stmts.extend(value_stmts)
        local_decl.extend(local_var)

    # Handle optional fields
    optional_fields = {field.lower().replace('-', '_'): (field, val)
                       for field, val in type_children.items()
                       if val.Optional == 'True'}
    # Check if all fields (including optional) are present; if not, use ..Default::default()
    all_field_names = {field.lower().replace('-', '_') for field in type_children}
    present_fields = set()
    for elem in seq.value:
        present_fields.add(elem.lower().replace('-', '_'))
    missing_non_optional = all_field_names - present_fields - set(optional_fields.keys())
    missing_optional = set(optional_fields.keys()) - present_fields
    for fd_name, (fd_orig, fd_data) in optional_fields.items():
        if fd_name in present_fields:
            # Build exist struct with all fields listed (avoid ::default() in statics)
            exist_parts = []
            for ofn in optional_fields:
                exist_parts.append(f'{ofn}: {"true" if ofn == fd_name else "false"}')
            fields.append(f'exist: {type_name_str}_exist {{ {", ".join(exist_parts)} }}')
            break
    else:
        if optional_fields:
            exist_parts = [f'{ofn}: false' for ofn in optional_fields]
            fields.append(f'exist: {type_name_str}_exist {{ {", ".join(exist_parts)} }}')

    # If any fields are missing (optional or not), use ..unsafe { std::mem::zeroed() }
    # (cannot use ..Default::default() in static contexts)
    if missing_non_optional or missing_optional:
        rust_string = f'{type_name_str} {{ {", ".join(fields)}, ..unsafe {{ std::mem::zeroed() }} }}'
    else:
        rust_string = f'{type_name_str} {{ {", ".join(fields)} }}'
    return stmts, str(rust_string), local_decl


@expression.register(ogAST.PrimSequenceOf)
def _sequence_of(seqof, **kwargs):
    stmts, local_decl = [], []
    # Use array_content for proper struct literal with type name and padding
    _, raw_str, _ = expression(seqof.value[0], readonly=1) if seqof.value else ('', '', [])
    result = array_content(seqof, '', seqof.exprType)
    return stmts, str(result), local_decl


@expression.register(ogAST.PrimChoiceItem)
def _choiceitem(choice, **kwargs):
    stmts, choice_str, local_decl = expression(choice.value['value'], readonly=1)
    bty = find_basic_type(choice.value['value'].exprType)

    if isinstance(choice.value['value'], (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
        if bty.kind.startswith('Integer'):
            choice_str = choice.value['value'].numeric_value
        elif bty.kind in ('IA5StringType', 'StringType'):
            choice_str = array_content(choice.value['value'], choice_str, choice.value['value'].exprType)
        else:
            choice_str = array_content(choice.value['value'], choice_str, bty)

    # Find the choice variant name
    basic = find_basic_type(choice.exprType)
    search = choice.value['choice'].lower().replace('-', '_')
    variant_name = 'CHOICE_NOT_FOUND'
    for each in basic.Children:
        curr_choice = each.lower().replace('-', '_')
        if curr_choice == search:
            variant_name = each.replace('-', '_')
            break

    # In Rust, CHOICE is an enum with data: EnumName::VariantName(value)
    type_name_str = type_name(choice.exprType)
    rust_string = f'{type_name_str}::{variant_name}({choice_str})'
    return stmts, str(rust_string), local_decl
