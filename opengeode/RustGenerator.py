@expression.register(ogAST.ExprPlus)
@expression.register(ogAST.ExprMul)
@expression.register(ogAST.ExprMinus)
@expression.register(ogAST.ExprGt)
@expression.register(ogAST.ExprGe)
@expression.register(ogAST.ExprLt)
@expression.register(ogAST.ExprLe)
@expression.register(ogAST.ExprDiv)
@expression.register(ogAST.ExprMod)
@expression.register(ogAST.ExprRem)
def _basic_operators(expr, **kwargs):
    code, local_decl = [], []
    left_stmts, left_str, left_local = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)

    # Map Ada operators to Rust operators
    op_map = {'+': '+', '-': '-', '*': '*', '/': '/',
              '>': '>', '>=': '>=', '<': '<', '<=': '<=',
              'mod': '%', 'rem': '%'}
    rust_op = op_map.get(expr.operand, expr.operand)

    lbty = find_basic_type(expr.left.exprType)
    rbty = find_basic_type(expr.right.exprType)

    if lbty.kind.startswith('Integer') and \
            isinstance(expr.right, (ogAST.PrimOctetStringLiteral,
                                    ogAST.PrimBitStringLiteral)):
        right_str = str(expr.right.numeric_value)
    if rbty.kind.startswith('Integer') and \
            isinstance(expr.left, (ogAST.PrimOctetStringLiteral,
                                   ogAST.PrimBitStringLiteral)):
        left_str = str(expr.left.numeric_value)

    rust_string = f'({left_str} {rust_op} {right_str})'

    code.extend(left_stmts)
    code.extend(right_stmts)
    local_decl.extend(left_local)
    local_decl.extend(right_local)
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprEq)
@expression.register(ogAST.ExprNeq)
def _equality(expr, **kwargs):
    code, left_str, local_decl = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)
    code.extend(right_stmts)
    local_decl.extend(right_local)

    asn1_type = getattr(expr.left.exprType, 'ReferencedTypeName', None)
    actual_type = type_name(expr.left.exprType)
    lbty = find_basic_type(expr.left.exprType)
    rbty = find_basic_type(expr.right.exprType)

    # Rust: == and !=
    rust_op = '==' if isinstance(expr, ogAST.ExprEq) else '!='

    basic = lbty.kind in ('IntegerType', 'Integer32Type', 'IntegerU8Type',
                          'BooleanType', 'EnumeratedType', 'ChoiceEnumeratedType')
    if basic:
        if isinstance(expr.right, (ogAST.PrimBitStringLiteral,
                                   ogAST.PrimOctetStringLiteral)):
            right_str = str(expr.right.numeric_value)
        rust_string = f'({left_str} {rust_op} {right_str})'
    else:
        if asn1_type in TYPES:
            if isinstance(expr.right, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
                if lbty.kind.startswith('Integer'):
                    right_str = str(expr.right.numeric_value)
                elif lbty.kind == 'IA5StringType':
                    right_str = ia5string_raw(expr.right)
                else:
                    right_str = array_content(expr.right, right_str, lbty)
            # Use _Equal function for complex types
            rust_string = f'{actual_type}_Equal(&{left_str}, &{right_str})'
            if isinstance(expr, ogAST.ExprNeq):
                rust_string = f'!{rust_string}'
        else:
            rust_string = f'({left_str} {rust_op} {right_str})'
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprAssign)
def _assign_expression(expr, **kwargs):
    '''Assignment expression'''
    code, local_decl = [], []
    strings = []
    left_stmts, left_str, left_local = expression(expr.left)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)

    basic_left = find_basic_type(expr.left.exprType)

    if basic_left.kind == 'IA5StringType' and \
            isinstance(expr.right, ogAST.PrimStringLiteral):
        # IA5String assignment
        def_value = ia5string_raw(expr.right)
        strings.append(f'{left_str} = {def_value};')
    elif basic_left.kind in ('SequenceOfType', 'OctetStringType', 'BitStringType'):
        if isinstance(expr.right, ogAST.PrimSubstring):
            strings.append(f'{left_str}.arr[..{right_str}.len()].copy_from_slice(&{right_str});')
        elif isinstance(expr.right, ogAST.ExprAppend):
            rlen = append_size(expr.right)
            strings.append(f'{left_str}.arr[..{rlen}].copy_from_slice(&{right_str});')
        elif isinstance(expr.right, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
            right_str = array_content(expr.right, right_str, basic_left)
            strings.append(f'{left_str} = {right_str};')
        else:
            strings.append(f'{left_str} = {right_str};')
        # Update n_count if variable-size
        if basic_left.Min != basic_left.Max:
            if isinstance(expr.right, ogAST.PrimSubstring):
                strings.append(f'{left_str}.n_count = {right_str}.len() as i32;')
            elif isinstance(expr.right, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
                count = len(expr.right.value) if hasattr(expr.right, 'value') else 0
                if isinstance(expr.right, ogAST.PrimStringLiteral):
                    count = len(expr.right.value) - 2
                strings.append(f'{left_str}.n_count = {count};')
    elif basic_left.kind.startswith('Integer') and \
            isinstance(expr.right, (ogAST.PrimOctetStringLiteral,
                                    ogAST.PrimBitStringLiteral)):
        right_str = str(expr.right.numeric_value)
        strings.append(f'{left_str} = {right_str};')
    elif basic_left.kind.startswith('Integer'):
        # Cast if needed
        basic_right = find_basic_type(expr.right.exprType)
        cast_left = type_name(basic_left)
        cast_right = type_name(basic_right)
        if cast_left != cast_right:
            res = f'{right_str} as {cast_left}'
        else:
            res = right_str
        strings.append(f'{left_str} = {res};')
    elif isinstance(expr.left, ogAST.PrimIndex):
        leftIsBitString = find_basic_type(expr.left.value[0].exprType).kind == 'BitStringType'
        rightIsBoolean = find_basic_type(expr.right.exprType).kind == 'BooleanType'
        if leftIsBitString and rightIsBoolean:
            if right_str.strip().lower() == 'true':
                res = '1'
            elif right_str.strip().lower() == 'false':
                res = '0'
            else:
                res = f'(if {right_str} {{ 1 }} else {{ 0 }})'
            strings.append(f'{left_str} = {res};')
        else:
            strings.append(f'{left_str} = {right_str};')
    else:
        strings.append(f'{left_str} = {right_str};')

    code.extend(left_stmts)
    code.extend(right_stmts)
    code.extend(strings)
    local_decl.extend(left_local)
    local_decl.extend(right_local)
    return code, '', local_decl


@expression.register(ogAST.ExprOr)
@expression.register(ogAST.ExprAnd)
@expression.register(ogAST.ExprXor)
@expression.register(ogAST.ExprImplies)
def _bitwise_operators(expr, **kwargs):
    code, local_decl = [], []
    left_stmts, left_str, left_local = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)

    basic_type = find_basic_type(expr.exprType)

    if basic_type.kind == 'BooleanType':
        if isinstance(expr, ogAST.ExprOr):
            rust_string = f'({left_str} || {right_str})'
        elif isinstance(expr, ogAST.ExprAnd):
            rust_string = f'({left_str} && {right_str})'
        elif isinstance(expr, ogAST.ExprXor):
            rust_string = f'({left_str} ^ {right_str})'
        elif isinstance(expr, ogAST.ExprImplies):
            rust_string = f'(!{left_str} || {right_str})'
    else:
        # Bitwise operations on non-boolean types
        if isinstance(expr, ogAST.ExprOr):
            rust_string = f'({left_str} | {right_str})'
        elif isinstance(expr, ogAST.ExprAnd):
            rust_string = f'({left_str} & {right_str})'
        elif isinstance(expr, ogAST.ExprXor):
            rust_string = f'({left_str} ^ {right_str})'
        elif isinstance(expr, ogAST.ExprImplies):
            rust_string = f'(!{left_str} | ({left_str} & {right_str}))'

    code.extend(left_stmts)
    code.extend(right_stmts)
    local_decl.extend(left_local)
    local_decl.extend(right_local)
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprNot)
def _not_expression(expr, **kwargs):
    code, local_decl = [], []
    expr_stmts, expr_str, expr_local = expression(expr.expr, readonly=1)

    bty_outer = find_basic_type(expr.exprType)
    if bty_outer.kind == 'BooleanType':
        rust_string = f'(!{expr_str})'
    elif 'Integer' in bty_outer.kind:
        try:
            max_val = int(bty_outer.Max)
            if max_val >= 0:
                mask = (1 << max_val.bit_length()) - 1
                rust_string = f'({expr_str} ^ {mask})'
            else:
                rust_string = f'(!{expr_str})'
        except (ValueError, TypeError, AttributeError):
            rust_string = f'(!{expr_str})'
    else:
        # Array/bitstring not
        rust_string = f'(!{expr_str})'

    code.extend(expr_stmts)
    local_decl.extend(expr_local)
    return code, str(rust_string), local_decl


