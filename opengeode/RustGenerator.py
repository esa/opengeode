# Process-level handler (the big one)
# ─────────────────────────────────────────────────────────────────────────

@generate.register(ogAST.Process)
def _process(process, simu=False, instance=False, taste=False, **kwargs):
    '''Generate the Rust code for a complete process (AST top level).

    Uses instance=True to generate code for a process type instance rather
    than the process type itself.
    '''
    if not instance:
        process.name = process.instance_of_name or process.processName
        generic = process.instance_of_name
        process_instance = process
        process = process.instance_of_ref or process
    else:
        process.name = process.processName
        generic = False
        process_instance = process

    global PROCESS_NAME
    PROCESS_NAME = process.name or process.processName
    global PROCESS
    PROCESS = process
    global GENERIC
    # When generating the process type module, all the code that can reach
    # a required interface (RI, timers, ...) is generic over the RI
    # implementation — the Rust equivalent of Ada's generic packages.
    GENERIC = bool(generic)

    global TASTE
    TASTE = taste

    global TYPES
    TYPES = process.dataview
    del OUT_SIGNALS[:]
    del PROCEDURES[:]
    simu_pi_decl = []
    OUT_SIGNALS.extend(process.output_signals)
    PROCEDURES.extend(process.procedures)
    global LPREFIX
    global NO_CONTEXT
    NO_CONTEXT = getattr(process, 'no_context', False)

    for each in PROCEDURES:
        process.random_generator.update(each.random_generator)

    stop_condition = kwargs["ppty_check"] if "ppty_check" in kwargs else ""

    has_context_params = any(mod.startswith("Context-")
                             for mod in process.asn1Modules)

    has_cs = any(process.cs_mapping.values())

    LOG.info(f'Generating Rust code for process {process.name}')

    # ── AST preprocessing (same as Ada/C) ──
    no_renames = Helper.code_generation_preprocessing(process)
    ALIASES.update(process.aliases)

    if not stop_condition:
        Helper.generate_asn1_datamodel(process)

    for (var_name, content) in process.variables.items():
        if var_name in no_renames:
            continue
        if var_name in process.aliases.keys():
            LOCAL_VAR[var_name] = content
        else:
            VARIABLES[var_name] = content

    MONITORS.update(process.monitors)

    process_level_decl = []
    reduced_statelist = {s for s in process.full_statelist
                         if s not in process.parallel_states}

    # ── RI stubs ──
    ri_stub_code = []

    # ── CHOICE selector functions ──
    # Choice selection conversion functions — skipped for Rust
    # In Rust, CHOICE is an enum and selection is done via pattern matching,
    # so these conversion functions are not needed.
    choice_selections = []

    # ── Context declarations ──
    context_decl = []
    if not stop_condition:
        # SDL constants (synonyms)
        for const in process.DV.SDL_Constants.values():
            bconst = find_basic_type(const.type)
            bkind = bconst.kind
            if bkind in ('IntegerType', 'RealType', 'NullType',
                         'BooleanType', 'Integer32Type', 'IntegerU8Type'):
                val = '()' if bkind == 'NullType' else const.value
                if isinstance(val, ogAST.PrimSelector):
                    _, val, _ = expression(const.value, readonly=1)
            else:
                _, val, _ = expression(const.value, readonly=1)
                if bkind in ('SequenceOfType', 'OctetStringType', 'BitStringType'):
                    val = array_content(const.value, val, bconst)
                elif bkind == 'IA5StringType':
                    # IA5 strings are fixed `arr: [u8; Max+1]` structs: build a
                    # proper struct literal, not a raw byte slice.
                    val = array_content(const.value, val, const.type)
                elif bkind == 'NullType':
                    val = '()'
                elif bkind not in ("EnumeratedType", "SequenceType"):
                    raise TypeError(f'Constant "{const.varName}" not ground')

            const_sort = const.type.ReferencedTypeName.replace('-', '_')
            if process.process_type and const.varName == 'self' and 'PID' in TYPES:
                # For process types, 'self' is the PID of this instance.
                # The static is emitted below (decoupled from this loop) and
                # the instance wrapper sets it at startup.
                continue
            elif const.varName == 'self':
                # Standalone process: 'self' is a constant (the PID of this
                # process in the environment)
                context_decl.append(
                    f'const SELF: {ASN1SCC}{const_sort} = {val};')
            else:
                context_decl.append(
                    f'const {const.varName.upper()}: {ASN1SCC}{const_sort} = {val};')

        # For process types with a PID type in the dataview, the PID of the
        # running instance is only known by the instance wrapper: keep it in
        # a pub(crate) static that the wrapper sets at startup. When the
        # dataview has no PID type nothing PID-related is emitted.
        if generic and 'PID' in TYPES:
            context_decl.append(
                f'pub(crate) static mut SELF_PID: {ASN1SCC}PID = '
                f'{ASN1SCC}PID::PID_env;')

        if not process.no_context:
            # Default context initialization. The static initializer must
            # contain only const-evaluable code: zeroed()/default() are
            # not const fn on rustc < 1.75 (E0015 in statics), so fields
            # without a user-specified initial value get a literal zero
            # built recursively from the type shape (const_zero_value).
            ctxt_parts = []
            for var_name, (var_type, def_value) in process.variables.items():
                if var_name in process.aliases.keys():
                    continue
                if def_value:
                    dst, dstr, dlocal = expression(def_value)
                    varbty = find_basic_type(var_type)
                    if varbty.kind.startswith('Integer') and \
                            isinstance(def_value, (ogAST.PrimOctetStringLiteral,
                                                   ogAST.PrimBitStringLiteral)):
                        dstr = str(def_value.numeric_value)
                    elif varbty.kind in ('SequenceOfType',
                                         'OctetStringType', 'BitStringType') \
                            and def_value.is_raw:
                        dstr = array_content(def_value, dstr, var_type)
                    elif varbty.kind in ('IA5StringType', 'StringType') and \
                            isinstance(def_value, ogAST.PrimStringLiteral):
                        dstr = array_content(def_value, dstr, var_type)
                    # The expression must be ground: it must not need any
                    # temporary variable to store a computed result
                    assert not dst and not dlocal, \
                            'DCL: Expecting a ground expression'
                    if '::default()' in dstr or 'zeroed()' in dstr:
                        # Replace the non-const call with a const literal
                        dstr = const_zero_value(var_type)
                    ctxt_parts.append(f'{var_name}: {dstr}')

            # Build the const-evaluable zero for the States enum: the
            # first declared state (any variant is a valid pre-init
            # value; the old code used zeroed(), i.e. discriminant 0)
            state_names = [s for s in process.mapping
                           if not s.endswith('START')] or \
                sorted(process.full_statelist)
            state_zero = None
            if state_names:
                first_state = state_names[0]
                state_zero = (
                    f'{ASN1SCC}{process.name.capitalize()}_States::'
                    f'{states_enum_id(first_state)}')

            if process.full_statelist and state_zero:
                if not any(p.startswith('state:') for p in ctxt_parts):
                    ctxt_parts.insert(0, f'state: {state_zero}')
            if process.has_instances and state_zero:
                # state-instance field (parallel-state instances)
                if not any(p.startswith('state_instance:') for p in ctxt_parts):
                    ctxt_parts.insert(0, f'state_instance: {state_zero}')
            if not any(p.startswith('init_done:') for p in ctxt_parts):
                ctxt_parts.insert(0, 'init_done: false')
            # Variables with no initial value: const-safe literal zero.
            # Skip the ones not present in the context struct (mirrors
            # Helper.generate_asn1_datamodel, which cannot reference them)
            for var_name, (var_type, def_value) in process.variables.items():
                if var_name in process.aliases.keys():
                    continue
                if getattr(var_type, 'ReferencedTypeName', None) is None:
                    continue
                if not any(p.startswith(f'{var_name}:') for p in ctxt_parts):
                    ctxt_parts.append(f'{var_name}: {const_zero_value(var_type)}')
            # Aggregate substates have a {substate}_state field each
            if state_zero:
                for substates in process.aggregates.values():
                    for each in substates:
                        fname = f'{each.statename.lower()}{SEPARATOR}state'
                        if not any(p.startswith(f'{fname}:') for p in ctxt_parts):
                            ctxt_parts.append(f'{fname}: {state_zero}')

            context_decl.append('// Default context with initial values')
            context_decl.append(
                f'static mut DEFAULT_CONTEXT: {ASN1SCC}{process.name.capitalize()}_Context = '
                f'{ASN1SCC}{process.name.capitalize()}_Context {{ '
                f'{", ".join(ctxt_parts)} }};')

            # ctxt mirrors DEFAULT_CONTEXT; the unsafe block is required
            # because statics are not Copy-in-place in stable Rust
            context_decl.append(
                f'static mut {LPREFIX}: {ASN1SCC}{process.name.capitalize()}_Context = '
                f'unsafe {{ DEFAULT_CONTEXT }};')

        # Monitors
        for mon_name, (mon_type, _) in process.monitors.items():
            # Static initializer: use a const literal, not Default::default()
            # (a non-const fn call in a static = E0015 on rustc < 1.75)
            context_decl.append(
                f'static mut {mon_name.upper()}: {type_name(mon_type)} = '
                f'{const_zero_value(mon_type)};')

        # Choice selections
        context_decl.extend(choice_selections)

    if stop_condition:
        # Static initializer must be const-evaluable (E0015 otherwise):
        # mirror the process context, all fields zero, using literals
        stop_ctxt_parts = []
        state_names = [s for s in process.mapping
                       if not s.endswith('START')] or \
            sorted(process.full_statelist)
        if state_names:
            first_state = state_names[0]
            stop_ctxt_parts.append(
                f'state: {ASN1SCC}{stop_condition}_States::'
                f'{states_enum_id(first_state, owner=stop_condition)}')
        stop_ctxt_parts.append('init_done: false')
        for var_name, (var_type, def_value) in process.variables.items():
            if var_name in process.aliases.keys():
                continue
            stop_ctxt_parts.append(f'{var_name}: {const_zero_value(var_type)}')
        context_decl.append(
            f'static mut {LPREFIX.upper()}: {ASN1SCC}{stop_condition}_Context = '
            f'{ASN1SCC}{stop_condition}_Context {{ '
            f'{", ".join(stop_ctxt_parts)} }};')

    # ── Aggregate START procedures ──
    aggreg_start_proc = []
    start_transition = []
    if not instance:
        for name, substates in process.aggregates.items():
            proc_name = f'{name}{SEPARATOR}START'
            # Rust does not need forward declarations (unlike Ada) — only
            # emit the definition, otherwise the name is defined twice.
            aggreg_start_proc.append(
                f'unsafe fn {proc_name}{ri_generic_sig()} {{')
            for subname in substates:
                aggreg_start_proc.append(
                    f'execute_branch_loop{ri_call_args([f"Branches::{subname.statename}{SEPARATOR}START"])};')
            aggreg_start_proc.append('}')
            aggreg_start_proc.append('')

        # Startup transition
        init_done = f'{LPREFIX}.init_done = true;' if not getattr(process, 'no_context', False) else ''
        rand_reset = []
        for rand_g in process.random_generator:
            rand_reset.append('unsafe { __OG_RNG_STATE = 0; }')

        if NO_CONTEXT:
            start_transition = [f'pub(crate) unsafe fn startup{ri_generic_sig()} {{}}', '']
        else:
            if process.transitions:
                start_transition = [
                    f'pub(crate) unsafe fn startup{ri_generic_sig()} {{',
                    *rand_reset,
                    f'{LPREFIX} = DEFAULT_CONTEXT;',
                    f'execute_transition{ri_call_args(["Branches::Startup_Transition"])};',
                    init_done,
                    '}',
                    '']
            else:
                start_transition = [
                    f'pub(crate) unsafe fn startup{ri_generic_sig()} {{',
                    *rand_reset,
                    f'{LPREFIX} = DEFAULT_CONTEXT;',
                    init_done,
                    '}',
                    '']
        if not TASTE:
            start_transition.extend([
                '// Auto-elaboration — call startup() before using the process'])
            # Note: startup() must be called by the harness before any PI calls

    # ── Main module header ──
    rust_body = [
        '// This file was generated automatically by OpenGEODE: DO NOT MODIFY IT!',
        '#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, unused_parens, unused_imports,',
        '         unused_variables, unused_mut, unused_assignments, dead_code)]',
        '',
    ]

    # Use statements for ASN.1 modules
    # asn1scc generates <stem>.rs and <stem>Def.rs from the input ASN.1 file
    # (e.g. dataview-uniq.rs for dataview-uniq.asn, datamodel.rs for
    # datamodel.asn). These files internally use 'use crate::<stem>Def::*;'
    # so we must declare the module with the exact name asn1scc expects.
    # When this is an instance wrapper, skip declaring dataview modules —
    # they are already declared in the process type module.
    dv_stem, dv_mod = dataview_rust_names(process)
    if not instance:
        try:
            for dv in process.asn1Modules:
                # Dataview type definitions and functions.
                # File name keeps the dash (dataview-uniqDef.rs); the Rust
                # module identifier uses an underscore (dataview_uniqDef).
                rust_body.append(f'#[path = "{dv_stem}Def.rs"]')
                rust_body.append(f'pub mod {dv_mod}Def;')
                rust_body.append(f'#[path = "{dv_stem}.rs"]')
                rust_body.append(f'pub mod {dv_mod};')
                # The asn1scc-generated <proc>_datamodel.rs imports the dataview
                # under the legacy fixed name 'dataview_uniq' (see the generator
                # post-processing and the test Makefile sed, which cannot know
                # the dataview file stem). Re-export the real module under that
                # name so any dataview file stem works.
                if dv_mod != 'dataview_uniq':
                    rust_body.append(f'pub use {dv_mod}Def as dataview_uniqDef;')
                    rust_body.append(f'pub use {dv_mod} as dataview_uniq;')
                rust_body.append(f'use {dv_mod}Def::*;')
                rust_body.append(f'use {dv_mod}::*;')
                break  # Only need one dataview module
            rust_body.append('use asn1rust::*;')
        except TypeError:
            rust_body.append('// No ASN.1 data types used in this model')
    else:
        # Instance wrapper: use types from the process type module
        ptype_module = process.instance_of_name.lower() if hasattr(process, 'instance_of_name') and process.instance_of_name else process.name.lower()
        rust_body.append(f'use {ptype_module}::{dv_mod}Def::*;')
        rust_body.append(f'use {ptype_module}::{dv_mod}::*;')
        # The datamodelDef module is declared by the process type module
        # (only when the type has a context). Re-export it here so that
        # code using the wrapper can reach the context types.
        if (getattr(process, 'instance_of_ref', None) is not None
                and not getattr(process.instance_of_ref, 'no_context', False)):
            rust_body.append(f'use {ptype_module}::{ptype_module}_datamodelDef::*;')
        rust_body.append('use asn1rust::*;')

    if not getattr(process, 'no_context', False) and not stop_condition and not instance:
        dmn = process.name.lower()
        # Datamodel definitions — module name must match asn1scc's internal 'use crate::<name>_datamodelDef::*;'
        rust_body.append(f'#[path = "{dmn}_datamodelDef.rs"]')
        rust_body.append(f'pub mod {dmn}_datamodelDef;')
        rust_body.append(f'use {dmn}_datamodelDef::*;')
        rust_body.append(f'#[path = "{dmn}_datamodel.rs"]')
        rust_body.append(f'pub mod {dmn}_datamodel;')
        rust_body.append(f'use {dmn}_datamodel::*;')

    # When this is a process instance wrapper (instance=True),
    # import the process type module (generated in the first call, instance=False)
    if instance and hasattr(process, 'instance_of_name') and process.instance_of_name:
        # process.instance_of_name is the type name (e.g., og_type)
        # The type file was generated as {instance_of_name}.rs
        ptype_module = process.instance_of_name.lower()
        rust_body.append(f'#[path = "{ptype_module}.rs"]')
        rust_body.append(f'pub mod {ptype_module};')
        # Include the user-editable RI stub file of THIS instance: it is the
        # single hook where the environment implements the required
        # interfaces (mirrors Ada's {instance}_RI package). The trait impl
        # below forwards every trait method to it.
        rust_body.append(f'#[path = "{process.name.lower()}_ri.rs"]')
        rust_body.append(f'mod {process.name.lower()}_ri;')
        rust_body.append(f'use {ptype_module}::*;')
    elif stop_condition:
        rust_body.append(f'mod {stop_condition.lower()}_datamodel;')
        rust_body.append(f'use {stop_condition.lower()}_datamodel::*;')

    if stop_condition:
        rust_body.append(f'mod {stop_condition.lower()};')
        rust_body.append(f'use {stop_condition.lower()}::*;')

    rust_body.append('')

    # Context declarations at module level
    if not instance:
        rust_body.extend(context_decl)

    # ── RI trait for process types ──
    # This is the Rust equivalent of the "with procedure" generic formals of
    # the Ada backend: one method per required interface. The instance
    # wrapper implements the trait so that the RI behaviour is supplied by
    # the instance (and its user-editable RI stub file) without any edit of
    # this generated module.
    ri_entries = []
    if generic and not stop_condition:
        ri_entries = external_ri_list(process, has_cs)
        rust_body.append(
            f'// Required interfaces of process type {process.name} '
            f'(implemented by the instance)')
        rust_body.append(f'pub trait {ri_trait_name()} {{')
        for entry in ri_entries:
            params = ', '.join(f'{n}: {t}' for n, t in entry['params'])
            rust_body.append('    #[allow(unused_variables)]')
            rust_body.append(
                f'    unsafe fn {entry["method"]}(&mut self, {params});')
        rust_body.append('}')
        rust_body.append('')

    if TASTE and not generic and not instance:
        c_ri_decls = []
        for sig in process.output_signals:
            signame = sig['name']
            # The TASTE glue (invoke_ri.c) provides {fn}_RI_{sig}_To_PID
            # with the destination PID as FIRST parameter (like the Ada
            # ri_adb binding). Without a PID type in the dataview the glue
            # exposes the plain {fn}_RI_{sig} function.
            if 'PID' in TYPES:
                param_spec = f'dest_pid: {ASN1SCC}PID'
                if 'type' in sig:
                    param_spec += f', param: *const {type_name(sig["type"])}'
                c_ri_decls.append(
                    f'    fn {process.name.lower()}_RI_{signame}_To_PID({param_spec});')
            else:
                param_spec = ''
                if 'type' in sig:
                    param_spec = f'param: *const {type_name(sig["type"])}'
                c_ri_decls.append(f'    fn {process.name.lower()}_RI_{signame}({param_spec});')
        for proc in process.procedures:
            if not proc.referenced:
                pname = proc.inputString
                params = []
                for fpar in proc.fpar:
                    ptype = type_name(fpar['type'])
                    pdir = fpar.get('direction', 'in')
                    if pdir in ('out', 'inout'):
                        params.append(f'{fpar["name"]}: *mut {ptype}')
                    else:
                        params.append(f'{fpar["name"]}: *const {ptype}')
                if 'PID' in TYPES:
                    params.append(f'default_sender: {ASN1SCC}PID')
                param_str = ', '.join(params)
                c_ri_decls.append(f'    fn {process.name.lower()}_RI_{pname}({param_str});')
        if c_ri_decls:
            rust_body.append('extern "C" {')
            rust_body.extend(c_ri_decls)
            rust_body.append('}')
            rust_body.append('')

    # ── Random generator declarations ──
    # The 'any' decision picks one of N answers at random. Implement this with
    # a small self-contained xorshift PRNG (no external `rand` crate, which the
    # generated Cargo.toml does not declare), seeded from the system clock so
    # that it really is random. The state is reset to 0 at each startup, which
    # forces a fresh seed on the first draw.
    if process.random_generator:
        rust_body.extend([
            'static mut __OG_RNG_STATE: u64 = 0;',
            'unsafe fn __og_rng_seed() {',
            '    // Seed from the system clock. Use unwrap_or_default (not a',
            '    // .map(...).unwrap_or(...) closure): the closure form makes the',
            '    // linker report duplicate #[no_mangle] symbols when this file is',
            '    // built both as a library and as a module of the test binary.',
            '    let nanos = std::time::SystemTime::now()',
            '        .duration_since(std::time::UNIX_EPOCH)',
            '        .unwrap_or_default()',
            '        .as_nanos() as u64;',
            '    __OG_RNG_STATE = if nanos == 0 { 0x9E3779B97F4A7C15 } else { nanos };',
            '}',
            'unsafe fn __og_rng_next() -> u64 {',
            '    if __OG_RNG_STATE == 0 {',
            '        __og_rng_seed();',
            '    }',
            '    let mut x = __OG_RNG_STATE;',
            '    x ^= x << 13; x ^= x >> 7; x ^= x << 17;',
            '    __OG_RNG_STATE = x;',
            '    x',
            '}',
        ])
    for each in process.random_generator:
        rust_body.extend([
            f'fn gen_{each}_init() -> u32 {{ unsafe {{ (__og_rng_next() % {each}) as u32 + 1 }} }}'])

    # ── CREATE symbol support ──
    if not instance and process.dependencies['create']:
        for each in process.dependencies['create']:
            rust_body.extend([
                f'extern "C" {{ fn {each.lower()}_create_instance(from: {ASN1SCC}PID) -> {ASN1SCC}PID; }}'])

    # ── Get_State function ──
    if not generic and not instance and not stop_condition and not NO_CONTEXT:
        rust_body.extend([
            f'#[no_mangle]',
            f'pub unsafe extern "C" fn {process.name.lower()}_state() -> *const u8 {{',
            f'    // Return state as C string - simplified',
            f'    std::ptr::null()',
            f'}}',
            ''])

    # ── Startup declaration ──
    if not generic:
        rust_body.extend([
            f'#[no_mangle]',
            f'pub unsafe extern "C" fn {process.name.lower()}_startup() {{',
            f'    startup();',
            f'}}',
            ''])

    # ── Inner procedures ──
    inner_procedures_code = []
    for proc in process.content.inner_procedures:
        not_local = False
        spelling = proc.inputString
        for p_decl in process.procedures:
            if p_decl.inputString.lower() == proc.inputString.lower() \
                    and p_decl.referenced:
                spelling = p_decl.inputString
                not_local = True
        proc_code, proc_local = generate(proc, is_rpc=not_local)
        process_level_decl.extend(proc_local)
        inner_procedures_code.extend(proc_code)
        if proc.exported:
            spelling = proc.inputString
            for p_decl in process.procedures:
                if p_decl.inputString.lower() == proc.inputString.lower() \
                        and p_decl.referenced:
                    spelling = p_decl.inputString
                    not_local = True
            if not proc.external and not generic:
                if not_local:
                    # Build PI wrapper with fpar parameters
                    pi_params = []
                    pi_args = []
                    for fpar in proc.fpar:
                        typename = type_name(fpar['type'])
                        pi_params.append(f'{fpar.get("name")}: &mut {typename}')
                        # Params are already &mut, pass directly (not &mut again)
                        pi_args.append(f'{fpar.get("name")}')
                    pi_param_str = ', '.join(pi_params)
                    pi_arg_str = ', '.join(pi_args)
                    rust_body.append(
                        f'#[no_mangle] pub unsafe extern "C" fn '
                        f'{process.name.lower()}_PI_{spelling}({pi_param_str}) {{ '
                        f'{proc.inputString}({pi_arg_str}); }}')
                else:
                    # Local exported procedure
                    pi_params = []
                    pi_args = []
                    for fpar in proc.fpar:
                        typename = type_name(fpar['type'])
                        pi_params.append(f'{fpar.get("name")}: &mut {typename}')
                        pi_args.append(f'{fpar.get("name")}')
                    pi_param_str = ', '.join(pi_params)
                    pi_arg_str = ', '.join(pi_args)
                    # Exported procedures are wrapped with the <process>_PI_
                    # prefix (C linkage), exactly like the referenced/not_local
                    # case above. Without the prefix an exported procedure
                    # named e.g. "check_queue" would clash with the runtime's
                    # <process>_check_queue service.
                    rust_body.append(
                        f'#[no_mangle] pub unsafe extern "C" fn '
                        f'{process.name.lower()}_PI_{spelling}({pi_param_str}) {{ '
                        f'{proc.inputString}({pi_arg_str}); }}')

    rust_body.extend(process_level_decl)

    # ── Observer state status ──
    if process.errorstates or process.ignorestates or process.successstates:
        obs = ['unsafe fn observer_state_status() -> asn1SccObserver_State_Kind {']
        obs.append(f'    match {LPREFIX}.state {{')
        if process.errorstates:
            for st in process.errorstates:
                obs.append(f'        {generate_state_name(st)} => {ASN1SCC}Error_State,')
        if process.ignorestates:
            for st in process.ignorestates:
                obs.append(f'        {generate_state_name(st)} => {ASN1SCC}Ignore_State,')
        if process.successstates:
            for st in process.successstates:
                obs.append(f'        {generate_state_name(st)} => {ASN1SCC}Success_State,')
        obs.append(f'        _ => {ASN1SCC}Regular_State,')
        obs.append('    }')
        obs.append('}')
        obs.append('')
        rust_body.extend(obs)

    rust_body.extend(inner_procedures_code)
    rust_body.extend(aggreg_start_proc)

    # ── Labels ──
    Helper.add_labels_before_each_branch(process)
    Helper.inner_labels_to_floating(process)

    # ── PI generation ──
    generated_pis = set()
    for signal in process.input_signals + [
                        {'name': timer} for timer in process.timers]:
        if stop_condition:
            break

        if 'renames' in signal and signal['renames'] is not None:
            continue

        signame = signal.get('name', 'START')
        if signame.lower() in generated_pis:
            continue
        generated_pis.add(signame.lower())
        fake_name = False

        ignore_export = False
        proc_to_declare = None
        for proc in process.procedures:
            if proc.inputString.lower() == signame.lower():
                ignore_export = True
                proc_to_declare = proc
                break

        if ignore_export:
            fake_name = f'{signame}_Transition'
            has_transition = any(signame.lower() == k.lower()
                                 for k in process.input_mapping.keys()) or has_cs
            if not has_transition and not instance:
                continue

        if signame == 'START':
            continue

        # PI parameter
        param_name = signal.get('param_name') or f'{signame}_param'
        param_decl = ''
        if 'type' in signal:
            typename = type_name(signal['type'])
            param_decl = f'{param_name}: &mut {typename}'

        pi_name = fake_name or signame

        # PI body
        rust_body.append(f'// Provided interface "{signame}"')

        if (not generic and not ignore_export) or (ignore_export and instance):
            # Export as C function. In TASTE the middleware glue calls
            # {process}_PI_{signal} (kazoo's vm_if wrapper); standalone
            # models export the plain SDL interface name, which the test
            # harnesses and user code call directly.
            if TASTE:
                export_name = f'{process.name.lower()}_PI_{signame}'
            else:
                export_name = pi_name
            sig = f'pub unsafe extern "C" fn {export_name}({param_decl})'
            rust_body.append(f'#[no_mangle]')
            rust_body.append(sig + ' {')
        elif generic:
            # Process type: PI is generic over the RI implementation. The
            # instance wrapper calls it with its own RI impl (the Rust
            # equivalent of instantiating the Ada generic package).
            rust_body.append(
                f'pub(crate) unsafe fn {pi_name}{ri_generic_sig([param_decl] if param_decl else [])} {{')
        else:
            if param_decl:
                rust_body.append(f'pub(crate) unsafe fn {pi_name}({param_decl}) {{')
            else:
                rust_body.append(f'pub(crate) unsafe fn {pi_name}() {{')

        has_transition = any(signame.lower() == k.lower()
                             for k in process.input_mapping.keys())

        if not instance:
            if has_transition and not getattr(process, 'no_context', False):
                rust_body.append(f'    match {LPREFIX}.state {{')

            def execute_transition(state, dest, simu_step=False):
                input_defs = process.input_mapping[signame].get(state)
                if not input_defs:
                    return False
                state_tree = state.split(SEPARATOR)
                context = process
                exitlist = []
                current = ''
                first_input_def = input_defs[0]
                trans = first_input_def and process.transitions[
                    first_input_def.transition_id]
                while state_tree:
                    current = current + state_tree.pop(0)
                    for comp in context.composite_states:
                        if current.lower() == comp.statename.lower():
                            if comp.exit_procedure:
                                exitlist.append(current)
                            context = comp
                            current = current + SEPARATOR
                            break
                for each in reversed(exitlist):
                    if trans and all(each.startswith(trans_st)
                                    for trans_st in trans.possible_states):
                        dest.append(
                            f'p{SEPARATOR}{each}{SEPARATOR}exit{ri_call_args()};')

                if first_input_def:
                    for inp in first_input_def.parameters:
                        dest.append(f'{LPREFIX}.{inp} = *{param_name};')

                    if len(input_defs) == 1:
                        if first_input_def.transition:
                            if simu_step:
                                dest.append(
                                    f'return Branches::{first_input_def.branch_label};')
                            else:
                                dest.append(
                                    f'execute_transition{ri_call_args([f"Branches::{first_input_def.branch_label}"])};')
                        else:
                            return False
                    else:
                        dest.append(
                            f'match {LPREFIX}.state_instance {{')
                        for inp_def in input_defs:
                            inst_name = inp_def.transition.possible_states[0]
                            dest.append(
                                f'{generate_state_name(inst_name)} =>')
                            if inp_def.transition:
                                dest.append(
                                    f'execute_transition{ri_call_args([f"Branches::{inp_def.branch_label}"])},')
                        dest.append(f'_ => execute_transition{ri_call_args(["Branches::Continuous_Signals"])},')
                        dest.append('}')
                else:
                    return False
                return True

            def case_state(state, dest, simu_step=False):
                if state.endswith('START'):
                    return
                statecase = [f'{generate_state_name(state)} => {{']
                input_def = process.input_mapping[signame].get(state)
                if state in process.aggregates.keys():
                    dest.extend(statecase)
                    dest.append('// State aggregation')
                    for sub in process.aggregates[state]:
                        if [a for a in sub.mapping.keys()
                                if a in process.input_mapping[signame].keys()]:
                            dest.append(
                                f'match {LPREFIX}.{sub.statename}{SEPARATOR}state {{')
                            for par in sub.mapping.keys():
                                case_state(par, dest, simu_step)
                            dest.append(
                                f'_ => execute_transition{ri_call_args(["Branches::Continuous_Signals"])},')
                            if simu:
                                dest.append('panic!("Lost_Input");')
                            dest.append('}')
                            break
                    else:
                        if input_def:
                            execute_transition(state, dest, simu_step)
                        else:
                            dest.append(
                                f'execute_transition{ri_call_args(["Branches::Continuous_Signals"])};')
                            if simu:
                                dest.append('panic!("Lost_Input");')
                    # Close the match arm
                    dest.append('}')
                else:
                    if execute_transition(state, statecase, simu_step):
                        dest.extend(statecase)
                        # Close the match arm
                        dest.append('}')

            if has_transition and not getattr(process, 'no_context', False):
                for each_state in reduced_statelist:
                    case_state(each_state, rust_body, False)
                rust_body.append('_ => {')
                rust_body.append(
                    f'execute_transition{ri_call_args(["Branches::Continuous_Signals"])};')
                if simu and fake_name is False:
                    rust_body.append('panic!("Lost_Input");')
                rust_body.append('}')
                rust_body.append('}')
            elif has_cs:
                rust_body.append(
                    f'execute_transition{ri_call_args(["Branches::Continuous_Signals"])};')
            else:
                rust_body.append('// no transition')

            if simu and fake_name is False and not generic:
                simu_code = []
                simu_code.append(
                    f'fn simu_{signame}({param_decl}) -> Branches {{')
                if has_transition and not getattr(process, 'no_context', False):
                    simu_code.append(f'match {LPREFIX}.state {{')
                    for each_state in reduced_statelist:
                        case_state(each_state, simu_code, True)
                    simu_code.append('_ => return Branches::Continuous_Signals;')
                    simu_code.append('}')
                elif has_cs:
                    simu_code.append('return Branches::Continuous_Signals;')
                else:
                    simu_code.append('return Branches::Branch_End;')
                simu_code.append('}')
                simu_code.append('')
                simu_pi_decl.append(simu_code)

        elif not fake_name or instance:
            # Instance wrapper: forward to the process type module with our
            # RI implementation — the analog of "package og_Instance is
            # new og_type (RI_0_rezult => Og_RI.rezult)" in the Ada backend.
            type_module = process.instance_of_name.lower() if hasattr(process, 'instance_of_name') and process.instance_of_name else process.name.lower()
            if 'type' in signal:
                call_args = [param_name]
            elif proc_to_declare and proc_to_declare.fpar:
                call_args = [p['name'] for p in proc_to_declare.fpar]
            else:
                call_args = []
            rust_body.append(
                f'let mut ri = {process.name.capitalize()}Ri;')
            args = ''.join(f', {a}' for a in call_args)
            rust_body.append(
                f'{type_module}::{signame}(&mut ri{args});')

        rust_body.append('}')
        rust_body.append('')

        if simu_pi_decl:
            for sc in simu_pi_decl:
                rust_body.extend(sc)

    # ── Continuous signals ──
    if has_cs:
        if not instance:
            cs_template = generate_code_for_continuous_signals(process, generic)
            rust_body.extend(cs_template)
        if not MONITORS and not generic:
            # If the model itself exports a procedure that maps to the
            # <process>_check_queue service (as test-save does), that user
            # implementation must be used instead of the runtime stub — emitting
            # both would define the symbol twice (E0428).
            has_user_check_queue = any(
                p.exported and p.inputString.lower() in
                (f'{process.name.lower()}_check_queue', 'check_queue')
                for p in process.procedures)
            if not has_user_check_queue:
                rust_body.extend([
                    f'#[no_mangle]',
                    f'pub unsafe extern "C" fn {process.name.lower()}_check_queue(res: &mut bool) {{',
                    f'    // Provided by runtime',
                    f'}}',
                    ''])

    # ── Instance startup ──
    if instance:
        type_module = process.instance_of_name.lower() if hasattr(process, 'instance_of_name') and process.instance_of_name else process.name.lower()
        startup_lines = ['unsafe fn startup() {']
        # The PID of this instance is only meaningful when the dataview
        # defines a PID type; the process type module declares SELF_PID
        # in that case only (mirrors the Ada "self" generic formal).
        if 'PID' in TYPES:
            startup_lines.append(
                f'    {type_module}::SELF_PID = '
                f'{ASN1SCC}PID::PID_{process.name.lower()};')
        startup_lines.append(
            f'    let mut ri = {process.name.capitalize()}Ri;')
        startup_lines.append(f'    {type_module}::startup(&mut ri);')
        startup_lines.append('}')
        startup_lines.append('')
        rust_body.extend(startup_lines)

    # ── Instance RI implementation ──
    # The instance implements the process type's RI trait. In TASTE the
    # middleware glue provides C functions for the message outputs and
    # the implicit services (get_sender, check_queue): those are called
    # directly through the extern "C" block below (this mirrors the Ada
    # backend, where kazoo's ri_adb template binds the instance's RI
    # package to the same C glue). The remaining entries (timers, other
    # external procedures, delete_instance, get_last_error) have no
    # unconditional glue: they are forwarded to the user-editable stubs
    # in {instance}_ri.rs (the analog of the Ada {instance}_RI package,
    # e.g. og_RI.ads/adb). The trait methods are derived from the process
    # TYPE node so that every method declared in the trait is implemented,
    # whatever this instance's wiring.
    if instance and process.instance_of_name:
        ptype_module = process.instance_of_name.lower()
        ptype_node = getattr(process, 'instance_of_ref', None) or process
        inst_ri_list = external_ri_list(ptype_node, has_cs)
        wiring = taste_instance_ri_wiring(
            inst_ri_list, ptype_node, has_cs) if TASTE else {}
        glue_extern = []
        # Message outputs: one glue function per output signal. The
        # signature of the glue function is derived from the signal
        # itself (dest_pid first, then a const pointer per parameter).
        inst_name = process.name.lower()
        for sig in ptype_node.output_signals:
            if TASTE and 'PID' in TYPES:
                sig_name = sig['name']
                glue = f'{inst_name}_RI_{sig_name}_To_PID'
                args = [f'dest_pid: {ASN1SCC}PID']
                if 'type' in sig:
                    typename = type_name(sig['type'])
                    param_name = sig.get('param_name') or f'{sig_name}_param'
                    args.append(f'{param_name}: *const {typename}')
                glue_extern.append(
                    f'    fn {glue}({", ".join(args)});')
        for entry in inst_ri_list:
            glue = wiring.get(entry['method'])
            if glue and entry['method'] == f'ri{SEPARATOR}get_sender':
                glue_extern.append(
                    f'    fn {glue}(sender_pid: *mut {ASN1SCC}PID, '
                    f'unused: {ASN1SCC}PID);')
            elif glue and entry['method'] == 'check_queue':
                glue_extern.append(
                    f'    fn {glue}(res: *mut bool);')
        if glue_extern:
            rust_body.append('// Middleware glue (C) implementing the '
                             'required interfaces of this instance')
            rust_body.append('extern "C" {')
            rust_body.extend(glue_extern)
            rust_body.append('}')
            rust_body.append('')
        rust_body.append(
            f'// RI implementation for instance {process.name} — '
            f'edit {process.name.lower()}_ri.rs')
        rust_body.append(f'pub struct {process.name.capitalize()}Ri;')
        rust_body.append('')
        rust_body.append(
            f'impl {ptype_module.capitalize()}Ri for '
            f'{process.name.capitalize()}Ri {{')
        for entry in inst_ri_list:
            params = ', '.join(f'{n}: {t}' for n, t in entry['params'])
            # User-facing stub name: plain SDL interface name
            stub_name = entry['method'].replace(f'ri{SEPARATOR}', '')
            stub_mod = f'{process.name.lower()}_ri'
            forward_args = ', '.join(n for n, _ in entry['params'])
            glue = wiring.get(entry['method'])
            body_lines = [
                f'    #[allow(unused_variables)]',
                f'    unsafe fn {entry["method"]}(&mut self, {params}) {{']
            if glue and entry['method'].startswith(f'ri{SEPARATOR}') \
                    and entry['method'] != f'ri{SEPARATOR}get_sender':
                # Message output: call the middleware glue. The glue takes
                # the destination PID first, then a const pointer per
                # message parameter (matching the C glue signature), while
                # the trait method receives (params..., dest_pid).
                glue_args = ['dest_pid']
                for pname, ptype in entry['params']:
                    if ptype == f'{ASN1SCC}PID':
                        continue
                    # ptype is '&mut T': pass a const pointer to the glue
                    glue_args.append(f'{pname} as *const _')
                body_lines.append(
                    f'        {glue}({", ".join(glue_args)});')
            elif glue and entry['method'] == f'ri{SEPARATOR}get_sender':
                body_lines.append(
                    f'        {glue}(sender as *mut _, dest_pid);')
            elif glue and entry['method'] == 'check_queue':
                body_lines.append(f'        {glue}(res as *mut bool);')
            else:
                body_lines.append(
                    f'        {stub_mod}::{stub_name}({forward_args});')
            body_lines.append('}')
            body_lines.append('')
            rust_body.extend(body_lines)
        rust_body.append('}')
        rust_body.append('')

    # ── RI declarations ──
    for signal in process.output_signals:
        sig = signal['name']
        param_name = signal.get('param_name') or f'{sig}_param'
        param_spec = ''
        if 'type' in signal:
            typename = type_name(signal['type'])
            if 'PID' in TYPES:
                param_spec = f'({param_name}: &mut {typename}, dest_pid: {ASN1SCC}PID)'
            else:
                param_spec = f'({param_name}: &mut {typename})'
        else:
            if 'PID' in TYPES:
                param_spec = f'(dest_pid: {ASN1SCC}PID)'
            else:
                param_spec = '()'

        if not instance and not generic:
            ri_stub_code.append(f'fn ri{SEPARATOR}{sig}{param_spec} {{ /* RI stub - implement me */ }}')

    # ── External procedure RIs ──
    for proc in (proc for proc in process.procedures if proc.external):
        sig = proc.inputString
        params = []
        for param in proc.fpar:
            typename = type_name(param['type'])
            params.append(f'{param["name"]}: &mut {typename}')
        if 'PID' in TYPES:
            if params:
                params_spec = f'({", ".join(params)}, dest_pid: {ASN1SCC}PID)'
            else:
                params_spec = f'(dest_pid: {ASN1SCC}PID)'
        else:
            params_spec = f'({", ".join(params)})' if params else '()'
        if not instance and not generic:
            ri_stub_code.append(f'fn ri{SEPARATOR}{sig}{params_spec} {{ /* RI stub */ }}')

    # ── Timer declarations ──
    for timer in process.timers:
        if stop_condition:
            break
        if not generic:
            if 'PID' in TYPES:
                ri_stub_code.append(
                    f'fn set_{timer}(val: &mut {ASN1SCC}T_UInt32, dest_pid: {ASN1SCC}PID) {{ /* timer stub */ }}')
                ri_stub_code.append(f'fn reset_{timer}(dest_pid: {ASN1SCC}PID) {{ /* timer stub */ }}')
            else:
                ri_stub_code.append(
                    f'fn set_{timer}(val: &mut {ASN1SCC}T_UInt32) {{ /* timer stub */ }}')
                ri_stub_code.append(f'fn reset_{timer}() {{ /* timer stub */ }}')

    # ── Branches enum ──
    all_labels = [lab.inputString for lab in process.content.floating_labels]
    if not instance and not NO_CONTEXT:
        branches = ', '.join(all_labels + ['Continuous_Signals', 'Branch_End'])
        rust_body.append(f'#[derive(Clone, Copy, PartialEq, Debug)]')
        # pub(crate): the enum is used in the signature of pub(crate) functions
        # (execute_transition, ...) — a private type there is an error (E0446)
        # on rustc < 1.74, and only a lint on newer compilers.
        rust_body.append(f'pub(crate) enum Branches {{ {branches} }}')
        rust_body.append('')

        if simu:
            rust_body.append('static mut BRANCH_COVERAGE: [bool; 256] = [false; 256];')

    # ── Transition code ──
    code_transitions = []
    local_decl_transitions = []
    for proc_tr in process.transitions:
        code_tr, tr_local_decl = generate(proc_tr)
        code_transitions.append(code_tr)
        local_decl_transitions.extend(tr_local_decl)

    # ── Floating labels as functions ──
    code_labels = []
    for label in process.content.floating_labels:
        if NO_CONTEXT:
            break
        # _floating_label generates the complete function (signature + body + closing brace)
        # so we just extend with its output
        code_label, _ = generate(label)
        rust_body.extend(code_label)

    # ── Execute_Transition and Execute_Branch_Loop ──
    if process.transitions and not instance and not NO_CONTEXT:
        if simu and not generic:
            rust_body.extend([
                f'#[no_mangle]',
                f'pub unsafe extern "C" fn {process.name.lower()}_simu_next(branch: Branches) -> Branches {{',
                '    let mut next_branch = branch;',
                '    match next_branch {'])
            for label in all_labels:
                rust_body.append(
                    f'        Branches::{label} => {{ BRANCH_COVERAGE[{list(all_labels).index(label)}] = true; '
                    f'next_branch = branch_{label}(); }}')
            if has_cs:
                rust_body.append(
                    '        Branches::Continuous_Signals => next_branch = branch_continuous_signals(),')
            else:
                rust_body.append(
                    '        Branches::Continuous_Signals => next_branch = Branches::Branch_End,')
            rust_body.append('        Branches::Branch_End => {}')
            rust_body.append('    }')
            rust_body.append('    next_branch')
            rust_body.append('}')
            rust_body.append('')

        # Declare local variables from transitions
        for decl in set(local_decl_transitions):
            rust_body.append(decl)

        rust_body.extend([
            f'unsafe fn execute_branch_loop{ri_generic_sig(["branch: Branches"])} {{',
            '    let mut next_branch = branch;',
            '    while next_branch != Branches::Branch_End {',
            '        match next_branch {'])
        for label in all_labels:
            rust_body.append(
                f'            Branches::{label} => next_branch = branch_{label}{ri_call_args()},')
        if has_cs:
            rust_body.append(
                f'            Branches::Continuous_Signals => next_branch = branch_continuous_signals{ri_call_args()},')
        else:
            rust_body.append(
                '            Branches::Continuous_Signals => next_branch = Branches::Branch_End,')
        rust_body.append('            Branches::Branch_End => {}')
        rust_body.append('        }')
        rust_body.append('    }')
        rust_body.append('}')
        rust_body.append('')

        rust_body.extend([
            f'pub(crate) unsafe fn execute_transition{ri_generic_sig(["branch: Branches"])} {{',
            f'    if !{LPREFIX}.init_done && branch != Branches::Startup_Transition {{',
            '        return;',
            '    }',
            f'    execute_branch_loop{ri_call_args(["branch"])};',
            '}',
            ''])

        rust_body.extend(code_labels)

    elif not instance and not NO_CONTEXT:
        rust_body.extend([
            f'pub(crate) unsafe fn execute_transition{ri_generic_sig(["branch: Branches"])} {{}}',
            ''])

    # ── Startup ──
    rust_body.extend(start_transition)

    # ── RI stubs ──
    if not TASTE and ri_stub_code:
        rust_body.append('// RI stubs - implement these in your code')
        rust_body.extend(ri_stub_code)

    # ── Cargo.toml ──
    # This Cargo.toml is written to <process>_cargo.toml.
    # The test Makefile should copy it to Cargo.toml (overwriting asn1scc's version).
    bin_section = "" if TASTE else '''
[[bin]]
name = "test_rust"
path = "main.rs"
'''
    cargo_toml = f'''[package]
name = "{process.name.lower()}"
version = "0.1.0"
edition = "2021"

[dependencies]
asn1rust = {{ path = "asn1rust" }}

[lib]
name = "{process.name.lower()}"
path = "{process.name.lower()}.rs"
crate-type = ["staticlib", "rlib"]
{bin_section}
[profile.release]
opt-level = 3
'''

    # ── Write files ──
    with open(process.name.lower() + os.extsep + 'rs', 'w') as rust_file:
        rust_file.write('\n'.join(format_rust_code(rust_body)))

    # Post-process: add 'use crate::<dv>::*;' to the asn1scc-generated
    # datamodel file so it can access dataview functions (IsConstraintValid, init, etc.)
    dmn = process.name.lower()
    dmn_rs = f'{dmn}_datamodel.rs'
    if os.path.exists(dmn_rs):
        with open(dmn_rs, 'r') as f:
            content = f.read()
        if 'use crate::dataview_uniq::' not in content and \
                f'use crate::{dv_mod}::' not in content:
            # Insert after the last 'use' line
            lines = content.split('\n')
            insert_idx = 0
            for i, line in enumerate(lines):
                if line.startswith('use '):
                    insert_idx = i + 1
            # Both the dataview *functions* module and the *type definitions*
            # module are needed: the generated init/IsConstraintValid code may
            # reference a dataview type (e.g. an enumerated type) whose Rust
            # definition lives in <dv>Def.
            lines.insert(insert_idx, f'use crate::{dv_mod}::*;')
            lines.insert(insert_idx + 1, f'use crate::{dv_mod}Def::*;')
            with open(dmn_rs, 'w') as f:
                f.write('\n'.join(lines))

    # Post-process: remove duplicate constant definitions from <dv>.rs
    # (they're already in <dv>Def.rs, causing ambiguity when both are glob-imported)
    dv_rs = f'{dv_stem}.rs'
    if os.path.exists(dv_rs):
        with open(dv_rs, 'r') as f:
            dv_content = f.read()
        # Comment out 'pub const' lines that duplicate <dv>Def.rs constants
        lines = dv_content.split('\n')
        new_lines = []
        skip_const_block = False
        for line in lines:
            if line.startswith('pub const '):
                # Skip duplicate constant definitions (they're in <dv>Def.rs)
                # These are single-line definitions ending with ;
                if line.rstrip().endswith(';'):
                    continue
                else:
                    skip_const_block = True
                    continue
            if skip_const_block:
                if ';' in line:
                    skip_const_block = False
                    continue
                continue
            new_lines.append(line)
        with open(dv_rs, 'w') as f:
            f.write('\n'.join(new_lines))

    if instance or not TASTE:
        # Write the user-editable RI stub file (only once, never clobbering
        # user edits). For a standalone process it mirrors the inline stubs;
        # for a process type INSTANCE it holds the required interfaces that
        # have no middleware glue (timers, other external procedures,
        # delete_instance, get_last_error) — the instance wrapper's trait
        # impl (above) forwards those to it, mirroring Ada's
        # {instance}_RI.ads/adb stub package. The message outputs and the
        # implicit services (get_sender, check_queue) are wired to the
        # middleware glue directly and are NOT part of the stub file.
        ri_stub_file = f'{process.name.lower()}_ri.rs'
        if not os.path.exists(ri_stub_file):
            stub_lines = []
            if instance and process.instance_of_name:
                # Instance of a process type: one plain-named function per
                # required interface of the TYPE (the trait impl in the
                # wrapper forwards to these — both derive from the type
                # node, so they always match).
                ptype_module = process.instance_of_name.lower()
                ptype_node = getattr(process, 'instance_of_ref', None) or process
                stub_lines = [
                    f'// RI stubs for instance {process.name} of process '
                    f'type {process.instance_of_name}',
                    '// Implement here the required interfaces (RI) of the',
                    '// process type that are not handled by the middleware',
                    '// (message outputs are sent by the TASTE glue).',
                    '// This file is generated only once and is',
                    '// never overwritten by the code generator.',
                    '#![allow(non_snake_case, non_camel_case_types, unused_variables, '
                    'unused_mut, dead_code)]',
                    f'use super::{ptype_module}::{dv_mod}Def::*;',
                    f'use super::{ptype_module}::{dv_mod}::*;',
                    f'use super::{ptype_module}::{ptype_module}_datamodelDef::*;'
                    if not getattr(process, 'instance_of_ref', None) or
                    not getattr(process.instance_of_ref, 'no_context', False)
                    else '',
                    '',
                ]
                hook_list = external_ri_list(ptype_node, has_cs)
                if TASTE:
                    # Only the entries without glue belong in the stub file
                    wiring = taste_instance_ri_wiring(
                        hook_list, ptype_node, has_cs)
                    hook_list = [e for e in hook_list
                                 if not wiring.get(e['method'])]
                for entry in hook_list:
                    params = ', '.join(f'{n}: {t}'
                                      for n, t in entry['params'])
                    stub_name = entry['method'].replace(f'ri{SEPARATOR}', '')
                    stub_lines.append(f'pub unsafe fn {stub_name}({params}) {{')
                    stub_lines.append('    // TODO: implement this RI')
                    stub_lines.append('}')
                    stub_lines.append('')
            elif ri_stub_code:
                stub_lines = [
                    f'// RI stubs for {process.name} - implement these functions',
                    '#![allow(non_snake_case, non_camel_case_types)]'] + ri_stub_code
            if stub_lines:
                with open(ri_stub_file, 'w') as ri_stub:
                    ri_stub.write(
                        '\n'.join(format_rust_code(stub_lines)))

    with open(f'{process.name.lower()}_cargo.toml', 'w') as cargo:
        cargo.write(cargo_toml)
    with open('Cargo.toml', 'w') as cargo:
        cargo.write(cargo_toml)

    # ── Generate instance if needed ──
    if process_instance is not process:
        process_instance.timers = process.timers
        process_instance.cs_mapping = process.cs_mapping
        generate(process_instance, simu, instance=True, taste=taste)


def write_statement(param, newline):
    '''Generate the code for the special "write" operator (Rust)'''
    code = []
    local = []
    basic_type = find_basic_type(param.exprType) or {}
    type_kind = basic_type.kind
    if isinstance(param, ogAST.ExprAppend):
        st1, _, lcl1 = write_statement(param.left, newline=False)
        st2, _, lcl2 = write_statement(param.right, newline=False)
        code.extend(st1)
        code.extend(st2)
        local.extend(lcl1)
        local.extend(lcl2)
    elif isinstance(param, ogAST.PrimConditional) and \
            type_kind.endswith('StringType'):
        # A conditional whose branches may have different string types (e.g.
        # IA5String vs OCTET STRING) cannot be one Rust value. Print each branch
        # according to its own type, selected by the condition — matching C.
        c_stmts, c_str, c_local = expression(param.value['if'], readonly=1)
        code.extend(c_stmts)
        local.extend(c_local)
        then_code, _, then_local = write_statement(param.value['then'], newline=False)
        else_code, _, else_local = write_statement(param.value['else'], newline=False)
        local.extend(then_local)
        local.extend(else_local)
        code.append(f'if {c_str} {{')
        code.extend(then_code)
        code.append('} else {')
        code.extend(else_code)
        code.append('}')
    elif type_kind == 'IA5StringType':
        code, string, local = expression(param, readonly=1)
        # asn1scc generates IA5String as a fixed `arr: [u8; Max+1]` array with a
        # null terminator (no n_count). Print the content up to the first NUL.
        code.append(
            f'{{ let _s = &{string};'
            f' let _n = _s.arr.iter().position(|&b| b == 0).unwrap_or(_s.arr.len());'
            f' print!("{{}}", String::from_utf8_lossy(&_s.arr[.._n])); }}')
    elif type_kind.endswith('StringType'):
        _k, _ms, has_n_count, _tn = _resolve_type_info(param.exprType, param.exprType)
        if isinstance(param, ogAST.PrimOctetStringLiteral):
            code.append(f'print!("{rust_escape_string(param.printable_string or "")}");')
        elif isinstance(param, ogAST.PrimStringLiteral):
            code.append(f'print!("{rust_string_from_literal(param.value[1:-1])}");')
        elif isinstance(param, ogAST.PrimConditional) and \
                isinstance(param.value.get('then'), ogAST.PrimStringLiteral) and \
                isinstance(param.value.get('else'), ogAST.PrimStringLiteral):
            # A conditional whose branches are string literals: print the text
            # directly (the generic branch below would treat the value as a
            # struct with n_count/arr, which a literal is not).
            c_stmts, c_str, c_local = expression(param.value['if'], readonly=1)
            code.extend(c_stmts)
            local.extend(c_local)
            then_txt = rust_string_from_literal(param.value['then'].value[1:-1])
            else_txt = rust_string_from_literal(param.value['else'].value[1:-1])
            code.append(f'print!("{{}}", if {c_str} {{ "{then_txt}" }} else {{ "{else_txt}" }});')
        else:
            # For OctetString/BitString variables, print as string content
            code, string, local = expression(param, readonly=1)
            if has_n_count:
                # Variable-size: print up to n_count
                code.append(f'{{ let _s = {string}; let n = _s.n_count as usize; print!("{{}}", String::from_utf8_lossy(&_s.arr[..n])); }}')
            else:
                # Fixed-size: no n_count; trim at the first NUL (if any)
                code.append(
                    f'{{ let _s = {string};'
                    f' let _n = _s.arr.iter().position(|&b| b == 0).unwrap_or(_s.arr.len());'
                    f' print!("{{}}", String::from_utf8_lossy(&_s.arr[.._n])); }}')
    elif type_kind in ('IntegerType', 'Integer32Type', 'IntegerU8Type'):
        code, string, local = expression(param, readonly=1)
        # Ada's 'Image adds a leading space for non-negative integers and none
        # for negative ones. Match that exactly.
        code.append(
            f'{{ let _v = {string};'
            f' if _v < 0 {{ print!("{{}}", _v); }} else {{ print!(" {{}}", _v); }} }}')
    elif type_kind == 'RealType':
        code, string, local = expression(param, readonly=1)
        # Ada's Float'Image: leading space for non-negative, scientific notation
        # Format: " d.ffffffffffffffE±dd" (1 digit before ., 14 after, 2-digit exp)
        code.append(f'{{ let _v = {string}; if _v >= 0.0 || _v.is_nan() {{ print!(" "); }} let _abs = _v.abs(); let _exp = _abs.log10().floor() as i32; let _mant = _v / 10f64.powi(_exp); print!("{{:.14}}E{{:+03}}", _mant, _exp); }}')
    elif type_kind == 'BooleanType':
        code, string, local = expression(param, readonly=1)
        code.append(f'print!("{{}}", if {string} {{ "TRUE" }} else {{ "FALSE" }});')
    elif type_kind in ('EnumeratedType', 'StateEnumeratedType',
                       'ChoiceEnumeratedType'):
        # Print the enumerant NAME (uppercased), matching the C/Ada backends.
        # A synthetic CHOICE-selection enum prints "<CHILD>_PRESENT".
        code, string, local = expression(param, readonly=1)
        enum_type = type_name(param.exprType)
        is_selection = enum_type.endswith('_Selection')
        ref = getattr(param.exprType, 'ReferencedTypeName', '') or ''
        basic = find_basic_type(param.exprType)
        variants = list((getattr(basic, 'EnumValues', None) or {}).items())
        if not variants and 'selection' in ref.replace('_', '-').lower():
            # Selection synonym: the parser has no EnumValues; reconstruct the
            # variants from the underlying CHOICE alternatives.
            choice = ref
            for suf in ('-Selection', '_Selection', '-selection', '_selection'):
                if choice.endswith(suf):
                    choice = choice[:-len(suf)]
                    break
            base = enum_type[len(ASN1SCC):]
            children = {}
            for tn, tdef in (TYPES or {}).items():
                if tn.replace('_', '-').lower() == choice.replace('_', '-').lower():
                    children = getattr(find_basic_type(tdef.type), 'Children', {}) or {}
                    break
            arms = []
            for cname in children:
                member = cname.replace('-', '_')
                vname = f'{base}_{member}_present'
                arms.append(f'{enum_type}::{vname} => '
                            f'print!("{member.upper()}_PRESENT")')
            code.append('match ' + string + ' { ' + ', '.join(arms) +
                        f', _ => {{}} }}' if arms else f'let _ = {string};')
        else:
            arms = []
            base = enum_type[len(ASN1SCC):] if enum_type.startswith(ASN1SCC) else enum_type
            for name, enumid in variants:
                printed = f'{name.upper()}_PRESENT' if is_selection else name.upper()
                if is_selection:
                    # Selection variants are "<Base>_<child>_present"; derive the
                    # child from the enumerant name and rebuild the exact spelling.
                    member = name
                    for suf in ('_present', '_PRESENT'):
                        if member.endswith(suf):
                            member = member[:-len(suf)]
                            break
                    member = member.rsplit('_', 1)[-1]
                    vname = f'{base}_{member}_present'
                else:
                    vname = getattr(enumid, 'EnumID', None) or name
                arms.append(f'{enum_type}::{vname} => print!("{printed}")')
            code.append('match ' + string + ' { ' + ', '.join(arms) +
                        f', _ => {{}} }}' if arms else f'let _ = {string};')
    else:
        code, string, local = expression(param, readonly=1)
        code.append(f'print!("{{:?}}", {string});')
    if newline:
        code.append('println!();')
    return code, '', local


