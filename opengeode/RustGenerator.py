def generate_code_for_continuous_signals(process, generic):
    '''Generate the code to handle continuous signals (Rust)'''
    cs_template = [
        '// Process continuous signals',
        'unsafe fn branch_continuous_signals() -> Branches {',
        'let mut message_pending: bool = true;',
    ]

    # Queue check
    if not MONITORS:
        cs_template.extend([
            f'if {LPREFIX}.init_done {{',
            'check_queue(&mut message_pending);',
            '}',
        ])
    else:
        cs_template.extend([
            '// Process observer transitions',
            'message_pending = false;',
        ])

    cs_template.extend([
        'if message_pending {',
        'return Branches::Branch_End;',
        '}',
    ])

    # Process continuous signals in state aggregations first
    done = []
    sep = 'if '
    last = ''
    need_final_end = False
    first_of_aggreg = True
    for cs, agg in product(process.cs_mapping.items(),
                           process.aggregates.items()):
        (statename, cs_item) = cs
        (agg_name, substates) = agg

        if not cs_item:
            continue
        for each in substates:
            if statename in each.cs_mapping and each.cs_mapping[statename]:
                if first_of_aggreg:
                    cs_template.append('let mut msg_pending = false;')
                    first_of_aggreg = False
                if statename not in done:
                    done.append(statename)
                substate = each.statename.lower()
                cs_template.extend([
                    f'{sep}{LPREFIX}.{substate}_0_state == '
                    f'{generate_state_name(each.statename)} {{',
                ])
                need_final_end = True
                for trans in cs_item:
                    cs_template.extend(generate_continuous_signal_code(
                        trans, process, statename))
                sep = 'else if '
                last = '}'
                break
    if need_final_end:
        cs_template.append('}')

    # Root-level continuous signals
    sep = 'if '
    for statename, cs_item in process.cs_mapping.items():
        if not cs_item or statename in done:
            continue
        # State instances check
        state_inst = ''
        for each in process.composite_states:
            state_names = getattr(each, 'state_names', None) or [each.statename]
            if statename.lower() in (s.lower() for s in state_names):
                if hasattr(each, 'instance_terminator'):
                    state_inst = (
                        f' && {LPREFIX}.state_instance == '
                        f'{generate_state_name(each.statename)}'
                    )
                    break

        cs_template.extend([
            f'{sep}{LPREFIX}.state == {generate_state_name(statename)}'
            f'{state_inst} {{',
        ])
        for trans in cs_item:
            cs_template.extend(generate_continuous_signal_code(
                trans, process, statename))
        sep = 'else if '

    if sep != 'if ':
        cs_template.append('}')

    cs_template.extend([
        'return Branches::Branch_End;',
        '}',
    ])

    return cs_template


def generate_continuous_signal_code(trans, process, statename):
    '''Generate code for a single continuous signal.

    The trigger can be a Decision node (for PROVIDED clauses) or a simple
    expression. When it is a Decision, we must call generate() (which
    dispatches to _decision) rather than expression(). This matches the
    Ada backend which calls generate(provided_clause.trigger, ...).
    '''
    code = []
    if trans.trigger:
        # Check if the trigger is a Decision node — if so, use generate()
        if isinstance(trans.trigger, ogAST.Decision):
            # The Decision handler generates if/elsif/else code.
            # Each answer's transition is the CS transition itself.
            trigger_code, trigger_local = generate(trans.trigger)
            code.extend(trigger_code)
            code.extend(trigger_local)
        else:
            # Simple expression trigger — generate an if condition
            stmts, cond_str, local = expression(trans.trigger)
            code.extend(stmts)
            code.extend(local)
            code.append(f'if {cond_str} {{')
            code.append(f'return Branches::Branch_{trans.statename};')
            code.append('}')
    return code


