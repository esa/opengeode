@generate.register(ogAST.Output)
@generate.register(ogAST.ProcedureCall)
def _call_external_function(output, **kwargs):
    '''Generate the code of a set of output or procedure call statements'''
    code = []
    code.extend(traceability(output))

    for out in output.output:
        signal_name = out['outputName']
        list_of_params = []
        call_code = []
        call_local = []

        if signal_name.lower() in ('write', 'writeln'):
            for param in out['params'][:-1]:
                stmts, _, local = write_statement(param, newline=False)
                if local:
                    code.append('{')
                    code.extend(local)
                    code.extend(stmts)
                    code.append('}')
                else:
                    code.extend(stmts)
            for param in out['params'][-1:]:
                stmts, _, local = write_statement(
                    param, newline=(signal_name.lower() == 'writeln'))
                if local:
                    code.append('{')
                    code.extend(local)
                    code.extend(stmts)
                    code.append('}')
                else:
                    code.extend(stmts)
            continue
        elif signal_name.lower() == 'reset_timer':
            param, = out['params']
            p_code, p_id, p_local = expression(param, readonly=1)
            p_id = canonical_timer_name(p_id)
            call_code.extend(p_code)
            call_local.extend(p_local)
            if 'PID' in TYPES:
                call_code.append(
                    f'ri.reset_{p_id}({default_dest_pid()});' if GENERIC
                    else f'reset_{p_id}({default_dest_pid()});')
            else:
                call_code.append(
                    f'ri.reset_{p_id}();' if GENERIC
                    else f'reset_{p_id}();')
            if call_local:
                code.append('{')
                code.extend(call_local)
                code.extend(call_code)
                code.append('}')
            else:
                code.extend(call_code)
            continue
        elif signal_name.lower() == 'set_timer':
            timer_value, timer_id = out['params']
            t_code, t_val, t_local = expression(timer_value)
            p_code, p_id, p_local = expression(timer_id)
            p_id = canonical_timer_name(p_id)
            call_code.extend(t_code)
            call_code.extend(p_code)
            call_local.extend(t_local)
            call_local.extend(p_local)
            tmp_id = f'tmp{out["tmpVars"][0]}'
            call_local.append(f'let mut {tmp_id}: {ASN1SCC}T_UInt32;')
            call_code.append(f'{tmp_id} = {t_val} as {ASN1SCC}T_UInt32;')
            if 'PID' in TYPES:
                call_code.append(
                    f'ri.set_{p_id}(&mut {tmp_id}, {default_dest_pid()});' if GENERIC
                    else f'set_{p_id}(&mut {tmp_id}, {default_dest_pid()});')
            else:
                call_code.append(
                    f'ri.set_{p_id}(&mut {tmp_id});' if GENERIC
                    else f'set_{p_id}(&mut {tmp_id});')
            if call_local:
                code.append('{')
                code.extend(call_local)
                code.extend(call_code)
                code.append('}')
            else:
                code.extend(call_code)
            continue

        is_transition_call = False
        proc, out_sig = None, None
        try:
            out_sig, = [sig for sig in OUT_SIGNALS
                        if sig['name'].lower() == signal_name.lower()]
        except ValueError:
            try:
                candidates = [sig for sig in PROCEDURES
                             if sig.inputString.lower() == signal_name.lower()]
                if not candidates:
                    raise ValueError
                proc = candidates[0] if len(candidates) == 1 else candidates[0]
                if proc.external:
                    out_sig = proc
            except ValueError:
                is_transition_call = False
                for sig in PROCEDURES:
                    if signal_name.lower() == f'{sig.inputString.lower()}_transition':
                        out_sig = sig
                        is_transition_call = True
                        break
                else:
                    LOG.warning(f'Could not find: {signal_name}')
                    return code, []

        if out_sig:
            # For _Transition calls (exported procedure RPC transitions),
            # the target is a PI function, not an RI — call without ri_ prefix
            if is_transition_call:
                # _Transition PI has no parameters
                call_code.append(f'{signal_name}{ri_call_args()};')
                code.extend(call_code)
                continue
            # Resolve dest_pid (for process types with PID)
            dest_pid = None
            if 'PID' in TYPES:
                to_dest = out.get('toDest')
                if not to_dest:
                    # No "TO xxx" -> environment (multicast), like Ada/C
                    dest_pid = default_dest_pid()
                elif isinstance(to_dest, ogAST.PrimVariable):
                    _, dest_pid, _ = expression(to_dest)
                else:
                    # A named PID: asn1scc -Rust under the renamePolicy 3
                    # used to build the dataview spells it PID_<name>
                    dest_pid = f'{ASN1SCC}PID::PID_' + \
                        str(to_dest).replace('-', '_').lower()
            for idx, param in enumerate(out.get('params') or []):
                param_direction = 'in'
                try:
                    param_type = out_sig['type']
                except TypeError:
                    param_type = out_sig.fpar[idx]['type']
                    param_direction = out_sig.fpar[idx]['direction']

                typename = type_name(param_type)
                p_code, p_id, p_local = expression(param, readonly=1)
                call_code.extend(p_code)
                call_local.extend(p_local)

                # Convert string literals to proper struct literals for CharString/OctetString types
                param_bty = find_basic_type(param.exprType)
                if isinstance(param, ogAST.PrimStringLiteral) and \
                        param_bty and param_bty.kind in ('IA5StringType', 'StringType', 'OctetStringType', 'BitStringType'):
                    # Use array_content with param_type (the RI parameter type) for correct type name
                    p_id = array_content(param, p_id, param_type)

                if param_direction == 'in' and not (
                        isinstance(param, ogAST.PrimVariable) and
                        p_id.startswith(LPREFIX)):
                    tmp_id = f'tmp{out["tmpVars"][idx]}'
                    call_local.append(f'let mut {tmp_id}: {typename} = Default::default();')
                    # The parameter type may differ in width from the source
                    # (e.g. length() yields i32 while the RI expects u64):
                    # cast explicitly, Rust has no implicit numeric coercion.
                    src_bty = find_basic_type(param.exprType)
                    tgt_bty = find_basic_type(param_type)
                    if src_bty.kind.startswith('Integer') and \
                            tgt_bty.kind.startswith('Integer') and \
                            type_name(param.exprType) != typename:
                        p_id = f'({p_id} as {typename})'
                    elif p_id in FPAR_VARS:
                        # Procedure formal parameters are received as &mut:
                        # dereference to assign the value into the temp.
                        p_id = f'*{p_id}'
                    call_code.append(f'{tmp_id} = {p_id};')
                    list_of_params.append(f'&mut {tmp_id}')
                else:
                    list_of_params.append(f'&mut {p_id}')

            name = out["outputName"]
            # In Rust, there are no default parameter values, so we must
            # always pass dest_pid when PID is in TYPES (the stub always
            # declares it). When toDest is not specified, use
            # default_dest_pid() — the environment (multicast), like the
            # Ada and C backends.
            is_signal = isinstance(out_sig, dict)
            if GENERIC:
                func_name = f'ri.ri{SEPARATOR}{name}'
            elif TASTE:
                # The middleware glue differs between the two kinds of RI:
                #  - output signals: {fn}_RI_{sig}_To_PID(dest_pid, params)
                #  - procedures:      {fn}_RI_{proc}(params, default_sender)
                if 'PID' in TYPES and is_signal:
                    func_name = f'{PROCESS.name.lower()}_RI_{name}_To_PID'
                else:
                    func_name = f'{PROCESS.name.lower()}_RI_{name}'
            else:
                func_name = f'ri{SEPARATOR}{name}'
            pos_params = ', '.join(list_of_params)
            if dest_pid is not None and TASTE and 'PID' in TYPES and not GENERIC:
                if is_signal:
                    # _To_PID glue takes the destination PID first
                    args = f'{dest_pid}, {pos_params}' if pos_params else dest_pid
                else:
                    # procedure glue takes the default sender last
                    args = f'{pos_params}, {dest_pid}' if pos_params else dest_pid
            elif dest_pid is not None:
                args = f'{pos_params}, {dest_pid}' if pos_params else dest_pid
            else:
                args = pos_params
            call_code.append(f'{func_name}({args});')
        else:
            ident = proc.inputString
            p = [p for p in PROCEDURES
                 if p.inputString.lower() == ident.lower() and not p.referenced][0]
            for idx, param in enumerate(out.get('params', [])):
                param_type = p.fpar[idx]['type']
                p_code, p_id, p_local = expression(param, readonly=1)
                call_code.extend(p_code)
                call_local.extend(p_local)
                # Procedure fpar params are &mut in Rust, so add &mut prefix
                list_of_params.append(f'&mut {p_id}')
            full_name = f'p{SEPARATOR}{proc.inputString}'
            if list_of_params:
                call_code.append(
                    f'{full_name}{ri_call_args(list_of_params)};')
            else:
                call_code.append(f'{full_name}{ri_call_args()};')

        if call_local:
            code.append('{')
            code.extend(call_local)
            code.extend(call_code)
            code.append('}')
        else:
            code.extend(call_code)

    return code, []


@generate.register(ogAST.TaskAssign)
def _task_assign(task, **kwargs):
    '''A list of assignments in a task symbol'''
    code, local_decl = [], []
    if hasattr(task, 'req_ids') and task.req_ids:
        code.extend(traceability(task))
    elif task.comment:
        code.extend(traceability(task.comment))
    for expr in task.elems:
        trace_comments = traceability(expr)
        try:
            code_assign, _, decl_assign = expression(expr)
        except TypeError as err:
            raise TypeError(f"{str(err)} - TaskAssign: '{task.inputString}'")
        if decl_assign:
            code.extend(trace_comments)
            code.append('{')
            code.extend(decl_assign)
            code.extend(code_assign)
            code.append('}')
        else:
            code.extend(trace_comments)
            code.extend(code_assign)
    return code, []


@generate.register(ogAST.TaskInformalText)
def _task_informal_text(task, **kwargs):
    '''Generate Rust comments for informal text'''
    code = []
    if hasattr(task, 'req_ids') and task.req_ids:
        code.extend(traceability(task))
    elif task.comment:
        code.extend(traceability(task.comment))
    # Each element may contain embedded newlines: comment EVERY line, otherwise
    # the continuation lines are emitted as bare (invalid) Rust code.
    for text in task.elems:
        for line in str(text).split('\n'):
            code.append('// ' + line)
    return code, []


@generate.register(ogAST.TaskForLoop)
def _task_forloop(task, **kwargs):
    '''For loops: range form and SEQUENCE OF iteration form'''
    stmt, local_decl = [], []
    local_scope = dict(LOCAL_VAR)
    if task.comment:
        stmt.extend(traceability(task.comment))
    stmt.extend(traceability(task))
    for loop in task.elems:
        if loop['range']:
            start_str, stop_str = '0', ''
            if loop['range']['start']:
                start_stmt, start_str, start_local = \
                    expression(loop['range']['start'])
                local_decl.extend(start_local)
                stmt.extend(start_stmt)

            stop_stmt, stop_str, stop_local = expression(loop['range']['stop'])
            local_decl.extend(stop_local)
            stmt.extend(stop_stmt)

            if loop['range']['step'] == 1:
                stmt.append(f'for {loop["var"]} in {start_str}..{stop_str} {{')
            else:
                stmt.append(f'let mut {loop["var"]} = {start_str};')
                stmt.append(f'while {loop["var"]} < {stop_str} {{')
            LOCAL_VAR.update({loop['var']: (loop['type'], None)})
        else:
            LOCAL_VAR.update({loop['var']: (loop['type'], None)})
            list_stmt, list_str, list_local = expression(loop['list'])
            basic_type = find_basic_type(loop['list'].exprType)
            stmt.extend(list_stmt)
            local_decl.extend(list_local)
            # list_str may be a block expression (e.g. a substring/slice),
            # which must be parenthesized before a field access or method call.
            iter_str = list_str
            if iter_str.strip().startswith('{'):
                iter_str = f'({iter_str})'
            # asn1scc wraps SEQUENCE OF / string types in a struct with an
            # `arr` field (and an `n_count` field when the size is variable).
            if isinstance(loop['list'], ogAST.PrimSubstring):
                # A slice returns a temporary struct: variable-size types carry
                # n_count, fixed-size ones only have the `arr` array.
                _k, _ms, _hn, _tn = _resolve_type_info(
                    loop['list'].exprType, loop['list'].exprType)
                if _hn:
                    range_str = f'0..{iter_str}.n_count as usize'
                else:
                    sub = loop['list'].value[1]['substring']
                    _s1, r1_str, _l1 = expression(sub[0])
                    _s2, r2_str, _l2 = expression(sub[1])
                    range_str = f'0..(({r2_str}) - ({r1_str}) + 1) as usize'
            elif basic_type.Min == basic_type.Max:
                range_str = f'0..{iter_str}.arr.len()'
            else:
                range_str = f'0..{iter_str}.n_count as usize'
            stmt.append(f'for {loop["var"]}_idx in {range_str} {{')
            # Bind the element as mutable: the loop body may pass a field of it
            # by mutable reference (procedure fpars are `&mut T`).
            stmt.append(f'let mut {loop["var"]} = {iter_str}.arr[{loop["var"]}_idx];')

        try:
            code_trans, local_trans = generate(loop['transition'])
            if local_trans:
                stmt.append('{')
                stmt.extend(set(local_trans))
            stmt.extend(code_trans)
            if local_trans:
                stmt.append('}')
        except AttributeError:
            stmt.append('// (empty transition)')

        if loop['range'] and loop['range']['step'] != 1:
            stmt.append(f'{loop["var"]} += {loop["range"]["step"]};')
        stmt.append('}')  # end for/while
    LOCAL_VAR.clear()
    LOCAL_VAR.update(local_scope)
    return stmt, local_decl


