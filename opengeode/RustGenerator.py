'''
    Rust code generator for OpenGEODE

    This module generates Rust code from SDL models, following the same
    architecture as AdaGenerator.py and CGenerator.py. It is designed to work
    with ASN.1 data types generated by asn1scc's Rust backend (flag: -Rust).

    The generated Rust code uses the asn1rust runtime library and the
    asn1Scc type prefix convention, matching the output of:
        asn1scc -Rust -typePrefix asn1Scc -equal *.asn

    All Helper.py functions (backend-independent) are used exactly as in
    the Ada and C backends:
        Helper.code_generation_preprocessing(process)
        Helper.generate_asn1_datamodel(process)
        Helper.add_labels_before_each_branch(process)
        Helper.inner_labels_to_floating(process)

    The code generation follows the same singledispatch pattern:
        generate(node) -> (code: List[str], local_decl: List[str])
        expression(node) -> (code: List[str], result_string: str, local_decl: List[str])
'''

