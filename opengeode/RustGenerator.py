@expression.register(ogAST.ExprPlus)
@expression.register(ogAST.ExprMul)
@expression.register(ogAST.ExprMinus)
@expression.register(ogAST.ExprGt)
@expression.register(ogAST.ExprGe)
@expression.register(ogAST.ExprLt)
@expression.register(ogAST.ExprLe)
@expression.register(ogAST.ExprDiv)
@expression.register(ogAST.ExprMod)
@expression.register(ogAST.ExprRem)
def _basic_operators(expr, **kwargs):
    code, local_decl = [], []
    left_stmts, left_str, left_local = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)

    # Map Ada operators to Rust operators
    op_map = {'+': '+', '-': '-', '*': '*', '/': '/',
              '>': '>', '>=': '>=', '<': '<', '<=': '<=',
              'mod': '%', 'rem': '%'}
    rust_op = op_map.get(expr.operand, expr.operand)

    lbty = find_basic_type(expr.left.exprType)
    rbty = find_basic_type(expr.right.exprType)

    if lbty.kind.startswith('Integer') and \
            isinstance(expr.right, (ogAST.PrimOctetStringLiteral,
                                    ogAST.PrimBitStringLiteral)):
        right_str = str(expr.right.numeric_value)
    if rbty.kind.startswith('Integer') and \
            isinstance(expr.left, (ogAST.PrimOctetStringLiteral,
                                   ogAST.PrimBitStringLiteral)):
        left_str = str(expr.left.numeric_value)

    rust_string = f'({left_str} {rust_op} {right_str})'

    code.extend(left_stmts)
    code.extend(right_stmts)
    local_decl.extend(left_local)
    local_decl.extend(right_local)
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprEq)
@expression.register(ogAST.ExprNeq)
def _equality(expr, **kwargs):
    code, left_str, local_decl = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)
    code.extend(right_stmts)
    local_decl.extend(right_local)

    asn1_type = getattr(expr.left.exprType, 'ReferencedTypeName', None)
    actual_type = type_name(expr.left.exprType)
    lbty = find_basic_type(expr.left.exprType)
    rbty = find_basic_type(expr.right.exprType)

    # Rust: == and !=
    rust_op = '==' if isinstance(expr, ogAST.ExprEq) else '!='

    basic = lbty.kind in ('IntegerType', 'Integer32Type', 'IntegerU8Type',
                          'BooleanType', 'EnumeratedType', 'ChoiceEnumeratedType')
    if basic:
        if isinstance(expr.right, (ogAST.PrimBitStringLiteral,
                                   ogAST.PrimOctetStringLiteral)):
            right_str = str(expr.right.numeric_value)
        rust_string = f'({left_str} {rust_op} {right_str})'
    else:
        if asn1_type in TYPES:
            if isinstance(expr.right, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
                if lbty.kind.startswith('Integer'):
                    right_str = str(expr.right.numeric_value)
                elif lbty.kind in ('IA5StringType', 'StringType'):
                    right_str = array_content(expr.right, right_str, expr.left.exprType)
                else:
                    right_str = array_content(expr.right, right_str, expr.left.exprType)
            # Use _Equal function for complex types
            # Wrap right_str in parentheses if it's a struct literal (starts with a type name + {)
            if right_str and ' { ' in right_str and right_str.startswith(ASN1SCC):
                rust_string = f'{actual_type}_Equal(&{left_str}, &({right_str}))'
            else:
                rust_string = f'{actual_type}_Equal(&{left_str}, &{right_str})'
            if isinstance(expr, ogAST.ExprNeq):
                rust_string = f'!{rust_string}'
        else:
            rust_string = f'({left_str} {rust_op} {right_str})'
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprAssign)
def _assign_expression(expr, **kwargs):
    '''Assignment expression'''
    code, local_decl = [], []
    strings = []
    left_stmts, left_str, left_local = expression(expr.left)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)

    basic_left = find_basic_type(expr.left.exprType)

    # Dereference fpar parameters on the left side (they are &mut references)
    if isinstance(expr.left, ogAST.PrimVariable):
        left_name = expr.left.value[0].split('.')[0]
        left_str = deref_fpar(left_str, left_name)

    if basic_left.kind == 'IA5StringType' and \
            isinstance(expr.right, ogAST.PrimStringLiteral):
        # IA5String assignment — convert to struct literal
        right_str = array_content(expr.right, right_str, expr.left.exprType)
        strings.append(f'{left_str} = {right_str};')
    elif basic_left.kind in ('SequenceOfType', 'OctetStringType', 'BitStringType'):
        if isinstance(expr.right, ogAST.PrimSubstring):
            # PrimSubstring now returns a struct with n_count and arr
            strings.append(f'{left_str} = {right_str};')
        elif isinstance(expr.right, ogAST.ExprAppend):
            # ExprAppend returns a block expression that creates a new concatenated array
            strings.append(f'{left_str} = {right_str};')
        elif isinstance(expr.right, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
            right_str = array_content(expr.right, right_str, expr.left.exprType)
            strings.append(f'{left_str} = {right_str};')
        else:
            strings.append(f'{left_str} = {right_str};')
        # Update n_count if variable-size (Min != Max)
        if basic_left.Min != basic_left.Max:
            if isinstance(expr.right, ogAST.PrimSubstring):
                # PrimSubstring returns a struct with n_count
                strings.append(f'{left_str}.n_count = {right_str}.n_count;')
            elif isinstance(expr.right, (ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
                count = len(expr.right.value) if hasattr(expr.right, 'value') else 0
                if isinstance(expr.right, ogAST.PrimStringLiteral):
                    count = len(expr.right.value) - 2
                strings.append(f'{left_str}.n_count = {count};')
    elif basic_left.kind.startswith('Integer') and \
            isinstance(expr.right, (ogAST.PrimOctetStringLiteral,
                                    ogAST.PrimBitStringLiteral)):
        right_str = str(expr.right.numeric_value)
        strings.append(f'{left_str} = {right_str};')
    elif basic_left.kind.startswith('Integer'):
        # Cast if needed
        basic_right = find_basic_type(expr.right.exprType)
        cast_left = type_name(basic_left)
        cast_right = type_name(basic_right)
        if cast_left != cast_right:
            res = f'{right_str} as {cast_left}'
        else:
            res = right_str
        strings.append(f'{left_str} = {res};')
    elif isinstance(expr.left, ogAST.PrimIndex):
        leftIsBitString = find_basic_type(expr.left.value[0].exprType).kind == 'BitStringType'
        rightIsBoolean = find_basic_type(expr.right.exprType).kind == 'BooleanType'
        if leftIsBitString and rightIsBoolean:
            if right_str.strip().lower() == 'true':
                res = '1'
            elif right_str.strip().lower() == 'false':
                res = '0'
            else:
                res = f'(if {right_str} {{ 1 }} else {{ 0 }})'
            strings.append(f'{left_str} = {res};')
        else:
            strings.append(f'{left_str} = {right_str};')
    else:
        strings.append(f'{left_str} = {right_str};')

    code.extend(left_stmts)
    code.extend(right_stmts)
    code.extend(strings)
    local_decl.extend(left_local)
    local_decl.extend(right_local)
    return code, '', local_decl


@expression.register(ogAST.ExprOr)
@expression.register(ogAST.ExprAnd)
@expression.register(ogAST.ExprXor)
@expression.register(ogAST.ExprImplies)
def _bitwise_operators(expr, **kwargs):
    code, local_decl = [], []
    left_stmts, left_str, left_local = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)

    basic_type = find_basic_type(expr.exprType)

    if basic_type.kind == 'BooleanType':
        if isinstance(expr, ogAST.ExprOr):
            rust_string = f'({left_str} || {right_str})'
        elif isinstance(expr, ogAST.ExprAnd):
            rust_string = f'({left_str} && {right_str})'
        elif isinstance(expr, ogAST.ExprXor):
            rust_string = f'({left_str} ^ {right_str})'
        elif isinstance(expr, ogAST.ExprImplies):
            rust_string = f'(!{left_str} || {right_str})'
    elif basic_type.kind == 'SequenceOfType':
        # Element-wise boolean operations on SEQUENCE OF Boolean
        elem_bty = find_basic_type(basic_type.type)
        if elem_bty.kind == 'BooleanType':
            # Generate element-wise operation as a block expression
            tmp = f'tmp{expr.tmpVar}'
            local_decl.append(f'let mut {tmp} = {left_str};')
            if isinstance(expr, ogAST.ExprAnd):
                loop_body = f'{tmp}.arr[i] &= {right_str}.arr[i];'
            elif isinstance(expr, ogAST.ExprOr):
                loop_body = f'{tmp}.arr[i] |= {right_str}.arr[i];'
            elif isinstance(expr, ogAST.ExprXor):
                loop_body = f'{tmp}.arr[i] ^= {right_str}.arr[i];'
            elif isinstance(expr, ogAST.ExprImplies):
                loop_body = f'{tmp}.arr[i] = !{tmp}.arr[i] || {right_str}.arr[i];'
            rust_string = f'{{ for i in 0..{tmp}.arr.len() {{ {loop_body} }} {tmp} }}'
        else:
            # Non-boolean SEQUENCE OF — fall back to bitwise
            if isinstance(expr, ogAST.ExprOr):
                rust_string = f'({left_str} | {right_str})'
            elif isinstance(expr, ogAST.ExprAnd):
                rust_string = f'({left_str} & {right_str})'
            elif isinstance(expr, ogAST.ExprXor):
                rust_string = f'({left_str} ^ {right_str})'
            elif isinstance(expr, ogAST.ExprImplies):
                rust_string = f'(!{left_str} | ({left_str} & {right_str}))'
    else:
        # Bitwise operations on non-boolean types
        if isinstance(expr, ogAST.ExprOr):
            rust_string = f'({left_str} | {right_str})'
        elif isinstance(expr, ogAST.ExprAnd):
            rust_string = f'({left_str} & {right_str})'
        elif isinstance(expr, ogAST.ExprXor):
            rust_string = f'({left_str} ^ {right_str})'
        elif isinstance(expr, ogAST.ExprImplies):
            rust_string = f'(!{left_str} | ({left_str} & {right_str}))'

    code.extend(left_stmts)
    code.extend(right_stmts)
    local_decl.extend(left_local)
    local_decl.extend(right_local)
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprNot)
def _not_expression(expr, **kwargs):
    code, local_decl = [], []
    expr_stmts, expr_str, expr_local = expression(expr.expr, readonly=1)

    bty_outer = find_basic_type(expr.exprType)
    # Dereference fpar parameters (they are &mut references)
    if isinstance(expr.expr, ogAST.PrimVariable):
        var_name = expr.expr.value[0].split('.')[0]
        expr_str = deref_fpar(expr_str, var_name)
    if bty_outer.kind == 'BooleanType':
        rust_string = f'(!{expr_str})'
    elif bty_outer.kind == 'SequenceOfType':
        # Element-wise NOT on SEQUENCE OF Boolean
        elem_bty = find_basic_type(bty_outer.type)
        if elem_bty.kind == 'BooleanType':
            # Generate as a block expression to avoid for...else syntax issues
            tmp = f'tmp{expr.tmpVar}'
            local_decl.append(f'let mut {tmp} = {expr_str};')
            # No statement code — the loop is embedded in the expression
            rust_string = f'{{ for i in 0..{tmp}.arr.len() {{ {tmp}.arr[i] = !{tmp}.arr[i]; }} {tmp} }}'
        else:
            try:
                max_val = int(bty_outer.Max)
                if max_val >= 0:
                    mask = (1 << max_val.bit_length()) - 1
                    rust_string = f'({expr_str} ^ {mask})'
                else:
                    rust_string = f'(!{expr_str})'
            except (ValueError, TypeError):
                rust_string = f'(!{expr_str})'
    elif 'Integer' in bty_outer.kind:
        try:
            max_val = int(bty_outer.Max)
            if max_val >= 0:
                mask = (1 << max_val.bit_length()) - 1
                rust_string = f'({expr_str} ^ {mask})'
            else:
                rust_string = f'(!{expr_str})'
        except (ValueError, TypeError, AttributeError):
            rust_string = f'(!{expr_str})'
    else:
        # Array/bitstring not
        rust_string = f'(!{expr_str})'

    code.extend(expr_stmts)
    local_decl.extend(expr_local)
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprNeg)
def _neg_expression(expr, **kwargs):
    code, local_decl = [], []
    expr_stmts, expr_str, expr_local = expression(expr.expr, readonly=1)
    cast = type_name(find_basic_type(expr.exprType))
    if not is_numeric(expr_str):
        rust_string = f'(-({expr_str} as {cast}))'
    else:
        rust_string = f'(-{expr_str})'
    code.extend(expr_stmts)
    local_decl.extend(expr_local)
    return code, str(rust_string), local_decl


@expression.register(ogAST.ExprAppend)
def _append(expr, **kwargs):
    stmts, rust_string, local_decl = [], '', []
    left_stmts, left_str, left_local = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)
    stmts.extend(left_stmts)
    stmts.extend(right_stmts)
    local_decl.extend(left_local)
    local_decl.extend(right_local)

    # In Rust, append for arrays means concatenation
    # For SEQUENCE OF / strings, we build a new array
    try:
        name_of_type = type_name(expr.expected_type)
    except (NotImplementedError, AttributeError):
        name_of_type = type_name(expr.left.exprType)

    # Determine if the type has n_count (variable-size) or not (fixed-size)
    bty = find_basic_type(expr.left.exprType)
    # Resolve through ReferenceType
    while bty and bty.kind == 'ReferenceType' and bty.ReferencedTypeName in TYPES:
        bty = find_basic_type(TYPES[bty.ReferencedTypeName].type)
    has_n_count = True
    # Check the actual type definition, not the expression's computed range
    ref_name = expr.left.exprType.ReferencedTypeName if hasattr(expr.left.exprType, 'ReferencedTypeName') else None
    if ref_name and ref_name in TYPES:
        actual_bty = find_basic_type(TYPES[ref_name].type)
        while actual_bty and actual_bty.kind == 'ReferenceType' and actual_bty.ReferencedTypeName in TYPES:
            actual_bty = find_basic_type(TYPES[actual_bty.ReferencedTypeName].type)
        if actual_bty and actual_bty.kind == 'SequenceOfType':
            try:
                has_n_count = int(actual_bty.Min) != int(actual_bty.Max)
            except (ValueError, TypeError):
                pass
    elif bty and bty.kind == 'SequenceOfType':
        try:
            has_n_count = int(bty.Min) != int(bty.Max)
        except (ValueError, TypeError):
            has_n_count = True

    # For string types (IA5String, OctetString), handle differently
    if bty and bty.kind in ('IA5StringType', 'StringType'):
        # String concatenation: copy bytes
        rust_string = (f'{{ let mut tmp = {name_of_type}::default();'
                       f' let l = {left_str}; let r = {right_str};'
                       f' let mut n = 0usize;'
                       f' for &b in &l.arr {{ if b == 0 {{ break; }} tmp.arr[n] = b; n += 1; }}'
                       f' for &b in &r.arr {{ if b == 0 {{ break; }} tmp.arr[n] = b; n += 1; }}'
                       f' tmp }}')
        return stmts, str(rust_string), local_decl

    # For PrimSubstring (slicing), we need to wrap the slice in a temp struct
    # For PrimSequenceOf literals, we need to use array_content
    # For variables/constants, they already have .n_count and .arr

    # Bind both left and right to temp variables to avoid huge inline expressions.
    # This is critical for nested ExprAppend (e.g. a // b // c).
    left_var = left_str
    right_var = right_str

    # If left is a PrimSequenceOf, use array_content to make a proper struct
    if isinstance(expr.left, ogAST.PrimSequenceOf):
        try:
            et = expr.expected_type
        except (NotImplementedError, AttributeError):
            et = expr.left.exprType
        left_var = array_content(expr.left, left_str, et)
    elif isinstance(expr.left, ogAST.PrimStringLiteral):
        # Use expected_type for correct type name resolution
        try:
            et = expr.expected_type
        except (NotImplementedError, AttributeError):
            et = expr.left.exprType
        left_var = array_content(expr.left, left_str, et)

    # If right is a PrimSequenceOf, use array_content
    if isinstance(expr.right, ogAST.PrimSequenceOf):
        try:
            et = expr.expected_type
        except (NotImplementedError, AttributeError):
            et = expr.right.exprType
        right_var = array_content(expr.right, right_str, et)
    elif isinstance(expr.right, ogAST.PrimStringLiteral):
        try:
            et = expr.expected_type
        except (NotImplementedError, AttributeError):
            et = expr.right.exprType
        right_var = array_content(expr.right, right_str, et)

    # If either side is a complex expression (ExprAppend, PrimSubstring, etc.),
    # bind it to a temp variable to keep the code readable and correct.
    if isinstance(expr.left, (ogAST.ExprAppend, ogAST.PrimSubstring)) or not isinstance(expr.left, (ogAST.PrimVariable, ogAST.PrimConstant)):
        tmp_l = f'tmp_app{expr.tmpVar}_l'
        local_decl.append(f'let {tmp_l} = {left_var};')
        left_var = tmp_l
    if isinstance(expr.right, (ogAST.ExprAppend, ogAST.PrimSubstring)) or not isinstance(expr.right, (ogAST.PrimVariable, ogAST.PrimConstant, ogAST.PrimSequenceOf, ogAST.PrimStringLiteral)):
        tmp_r = f'tmp_app{expr.tmpVar}_r'
        local_decl.append(f'let {tmp_r} = {right_var};')
        right_var = tmp_r

    if has_n_count:
        rust_string = (f'{{ let mut tmp = {name_of_type}::default();'
                       f' tmp.arr[..{left_var}.n_count as usize].copy_from_slice(&{left_var}.arr[..{left_var}.n_count as usize]);'
                       f' tmp.arr[{left_var}.n_count as usize..{left_var}.n_count as usize + {right_var}.n_count as usize].copy_from_slice(&{right_var}.arr[..{right_var}.n_count as usize]);'
                       f' tmp.n_count = {left_var}.n_count + {right_var}.n_count;'
                       f' tmp }}')
    else:
        # Fixed-size: no n_count, just concatenate arrays
        try:
            arr_size = int(bty.Max)
        except (ValueError, TypeError):
            arr_size = 0
        rust_string = (f'{{ let mut tmp = {name_of_type}::default();'
                       f' tmp.arr[..{arr_size}].copy_from_slice(&{left_var}.arr[..{arr_size}]);'
                       f' tmp.arr[{arr_size}..{arr_size} + {arr_size}].copy_from_slice(&{right_var}.arr[..{arr_size}]);'
                       f' tmp }}')

    return stmts, str(rust_string), local_decl


@expression.register(ogAST.ExprIn)
def _expr_in(expr, **kwargs):
    stmts, local_decl = [], []
    left_stmts, left_str, left_local = expression(expr.left, readonly=1)
    right_stmts, right_str, right_local = expression(expr.right, readonly=1)
    local_decl.extend(left_local)
    local_decl.extend(right_local)
    stmts.extend(left_stmts)
    stmts.extend(right_stmts)

    if isinstance(expr.left, ogAST.PrimSequenceOf):
        # x in {1,2,3} -> check if right is in the raw array
        # Use expression() to get each element's value (handles PrimEnumeratedValue, PrimInteger, etc.)
        elem_strs = []
        for v in expr.left.value:
            v_stmts, v_str, v_local = expression(v, readonly=1)
            stmts.extend(v_stmts)
            local_decl.extend(v_local)
            elem_strs.append(v_str)
        rust_string = f'[{", ".join(elem_strs)}].contains(&{right_str})'
    else:
        # x in seqof -> iterate
        tmp = f'tmp{expr.tmpVar}'
        local_decl.append(f'let mut {tmp}: bool = false;')
        # Check if the left side is a fixed-size SEQUENCE OF (no n_count field)
        left_bty = find_basic_type(expr.left.exprType)
        if left_bty and hasattr(left_bty, 'Min') and hasattr(left_bty, 'Max') and left_bty.Min == left_bty.Max:
            stmts.append(f'for i in 0..{left_str}.arr.len() {{')
        else:
            stmts.append(f'for i in 0..{left_str}.n_count as usize {{')
        stmts.append(f'    if {left_str}.arr[i] == {right_str} {{')
        stmts.append(f'        {tmp} = true;')
        stmts.append(f'        break;')
        stmts.append(f'    }}')
        stmts.append(f'}}')
        rust_string = tmp

    return stmts, str(rust_string), local_decl


@expression.register(ogAST.PrimEnumeratedValue)
def _enumerated_value(primary, **kwargs):
    enumerant = primary.value[0].replace('_', '-').lower()
    basic = find_basic_type(primary.exprType)
    for each in basic.EnumValues:
        if each.lower() == enumerant:
            break
    use_prefix = getattr(basic.EnumValues[each], "IsStandardEnum", True)
    # In Rust, enum variants are scoped: EnumName::VariantName
    enum_id = basic.EnumValues[each].EnumID
    # Get the enum type name (e.g., asn1SccEnum_T)
    if hasattr(primary.exprType, 'ReferencedTypeName'):
        enum_type = f'{ASN1SCC}{primary.exprType.ReferencedTypeName.replace("-", "_")}'
    elif hasattr(basic, 'ReferencedTypeName'):
        enum_type = f'{ASN1SCC}{basic.ReferencedTypeName.replace("-", "_")}'
    else:
        enum_type = type_name(basic, use_prefix=use_prefix)
    # ASN1SCC Rust generates enum variants as asn1Scc{value}
    rust_string = f'{enum_type}::{ASN1SCC}{enum_id}'
    # For state enums, need the full path
    if basic.kind == 'StateEnumeratedType':
        rust_string = f'{ASN1SCC}{PROCESS_NAME.capitalize()}_States::{ASN1SCC}{enum_id}'
    return [], str(rust_string), []


