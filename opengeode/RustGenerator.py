@generate.register(ogAST.Process)
def _process(process, simu=False, instance=False, taste=False, **kwargs):
    '''Generate the Rust code for a complete process (AST top level).

    Uses instance=True to generate code for a process type instance rather
    than the process type itself.
    '''
    if not instance:
        process.name = process.instance_of_name or process.processName
        generic = process.instance_of_name
        process_instance = process
        process = process.instance_of_ref or process
    else:
        process.name = process.processName
        generic = False
        process_instance = process

    global PROCESS_NAME
    PROCESS_NAME = process.name
    global PROCESS
    PROCESS = process

    global TYPES
    TYPES = process.dataview
    del OUT_SIGNALS[:]
    del PROCEDURES[:]
    simu_pi_decl = []
    OUT_SIGNALS.extend(process.output_signals)
    PROCEDURES.extend(process.procedures)
    global LPREFIX
    global NO_CONTEXT
    NO_CONTEXT = getattr(process, 'no_context', False)

    for each in PROCEDURES:
        process.random_generator.update(each.random_generator)

    stop_condition = kwargs["ppty_check"] if "ppty_check" in kwargs else ""

    has_context_params = any(mod.startswith("Context-")
                             for mod in process.asn1Modules)

    has_cs = any(process.cs_mapping.values())

    LOG.info(f'Generating Rust code for process {process.name}')

    # ── AST preprocessing (same as Ada/C) ──
    no_renames = Helper.code_generation_preprocessing(process)
    ALIASES.update(process.aliases)

    if not stop_condition:
        Helper.generate_asn1_datamodel(process)

    for (var_name, content) in process.variables.items():
        if var_name in no_renames:
            continue
        if var_name in process.aliases.keys():
            LOCAL_VAR[var_name] = content
        else:
            VARIABLES[var_name] = content

    MONITORS.update(process.monitors)

    process_level_decl = []
    reduced_statelist = {s for s in process.full_statelist
                         if s not in process.parallel_states}

    # ── RI stubs ──
    ri_stub_code = []

    # ── CHOICE selector functions ──
    # Choice selection conversion functions — skipped for Rust
    # In Rust, CHOICE is an enum and selection is done via pattern matching,
    # so these conversion functions are not needed.
    choice_selections = []

    # ── Context declarations ──
    context_decl = []
    if not stop_condition:
        # SDL constants (synonyms)
        for const in process.DV.SDL_Constants.values():
            bconst = find_basic_type(const.type)
            bkind = bconst.kind
            if bkind in ('IntegerType', 'RealType', 'NullType',
                         'BooleanType', 'Integer32Type', 'IntegerU8Type'):
                val = const.value
                if isinstance(val, ogAST.PrimSelector):
                    _, val, _ = expression(const.value, readonly=1)
            else:
                _, val, _ = expression(const.value, readonly=1)
                if bkind in ('SequenceOfType', 'OctetStringType', 'BitStringType'):
                    val = array_content(const.value, val, bconst)
                elif bkind == 'IA5StringType':
                    val = ia5string_raw(const.value)
                elif bkind == 'NullType':
                    val = '0'
                elif bkind not in ("EnumeratedType", "SequenceType"):
                    raise TypeError(f'Constant "{const.varName}" not ground')

            const_sort = const.type.ReferencedTypeName.replace('-', '_')
            if process.process_type and const.varName == 'self' and 'PID' in TYPES:
                pass
            else:
                context_decl.append(
                    f'const {const.varName.upper()}: {ASN1SCC}{const_sort} = {val};')

        if not process.no_context:
            # Default context initialization
            ctxt_parts = []
            for var_name, (var_type, def_value) in process.variables.items():
                if var_name in process.aliases.keys():
                    continue
                if def_value:
                    dst, dstr, dlocal = expression(def_value)
                    varbty = find_basic_type(var_type)
                    if varbty.kind.startswith('Integer') and \
                            isinstance(def_value, (ogAST.PrimOctetStringLiteral,
                                                   ogAST.PrimBitStringLiteral)):
                        dstr = str(def_value.numeric_value)
                    elif varbty.kind in ('SequenceOfType',
                                         'OctetStringType', 'BitStringType') \
                            and def_value.is_raw:
                        dstr = array_content(def_value, dstr, varbty)
                    elif varbty.kind == 'IA5StringType' and \
                            isinstance(def_value, ogAST.PrimStringLiteral):
                        dstr = ia5string_raw(def_value)
                    ctxt_parts.append(f'{var_name}: {dstr}')

            if ctxt_parts:
                context_decl.append(
                    f'// Default context with initial values')
                context_decl.append(
                    f'static mut DEFAULT_CONTEXT: {ASN1SCC}{process.name.capitalize()}_Context = '
                    f'unsafe {{ std::mem::zeroed() }};')
            else:
                context_decl.append(
                    f'static mut DEFAULT_CONTEXT: {ASN1SCC}{process.name.capitalize()}_Context = '
                    f'unsafe {{ std::mem::zeroed() }};')

            context_decl.append(
                f'static mut {LPREFIX}: {ASN1SCC}{process.name.capitalize()}_Context = '
                f'unsafe {{ std::mem::zeroed() }};')

        # Monitors
        for mon_name, (mon_type, _) in process.monitors.items():
            context_decl.append(
                f'static mut {mon_name.upper()}: {type_name(mon_type)} = Default::default();')

        # Choice selections
        context_decl.extend(choice_selections)

    if stop_condition:
        context_decl.append(
            f'static mut {LPREFIX.upper()}: {ASN1SCC}{stop_condition}_Context = '
            f'{ASN1SCC}{stop_condition}_Context {{ ..Default::default() }};')

    # ── Aggregate START procedures ──
    aggreg_start_proc = []
    start_transition = []
    if not instance:
        for name, substates in process.aggregates.items():
            proc_name = f'{name}{SEPARATOR}START'
            process_level_decl.append(f'unsafe fn {proc_name}();')
            aggreg_start_proc.append(f'unsafe fn {proc_name}() {{')
            for subname in substates:
                aggreg_start_proc.append(
                    f'execute_branch_loop(Branches::{subname.statename}{SEPARATOR}START);')
            aggreg_start_proc.append('}')
            aggreg_start_proc.append('')

        # Startup transition
        init_done = f'{LPREFIX}.init_done = true;' if not getattr(process, 'no_context', False) else ''
        rand_reset = []
        for rand_g in process.random_generator:
            rand_reset.append(f'gen_{rand_g}.reset();')

        if NO_CONTEXT:
            start_transition = ['unsafe fn startup() {}', '']
        else:
            if process.transitions:
                start_transition = [
                    'unsafe fn startup() {',
                    *rand_reset,
                    'execute_transition(Branches::Startup_Transition);',
                    init_done,
                    '}',
                    '']
            else:
                start_transition = [
                    'unsafe fn startup() {',
                    *rand_reset,
                    init_done,
                    '}',
                    '']
        if not taste:
            start_transition.extend([
                '// Auto-elaboration — call startup() before using the process'])
            # Note: startup() must be called by the harness before any PI calls

    # ── Main module header ──
    rust_body = [
        '// This file was generated automatically by OpenGEODE: DO NOT MODIFY IT!',
        '#![allow(non_snake_case, non_upper_case_globals, unused_parens, unused_imports,',
        '         unused_variables, unused_mut, unused_assignments, dead_code)]',
        '',
    ]

    # Use statements for ASN.1 modules
    # asn1scc generates dataview-uniq.rs and dataview-uniqDef.rs
    # These files internally use 'use crate::dataview_uniqDef::*;' so we must
    # declare the module with the exact name asn1scc expects.
    try:
        for dv in process.asn1Modules:
            # Dataview type definitions and functions
            # Module name must be 'dataview_uniqDef' (matching asn1scc's internal use)
            rust_body.append(f'#[path = "dataview-uniqDef.rs"]')
            rust_body.append(f'pub mod dataview_uniqDef;')
            rust_body.append(f'use dataview_uniqDef::*;')
            rust_body.append(f'#[path = "dataview-uniq.rs"]')
            rust_body.append(f'pub mod dataview_uniq;')
            rust_body.append(f'use dataview_uniq::*;')
            break  # Only need one dataview module
        rust_body.append('use asn1rust::*;')
    except TypeError:
        rust_body.append('// No ASN.1 data types used in this model')

    if not getattr(process, 'no_context', False) and not stop_condition:
        dmn = process.name.lower()
        # Datamodel definitions — module name must match asn1scc's internal 'use crate::<name>_datamodelDef::*;'
        rust_body.append(f'#[path = "{dmn}_datamodelDef.rs"]')
        rust_body.append(f'pub mod {dmn}_datamodelDef;')
        rust_body.append(f'use {dmn}_datamodelDef::*;')
        rust_body.append(f'#[path = "{dmn}_datamodel.rs"]')
        rust_body.append(f'pub mod {dmn}_datamodel;')
        rust_body.append(f'use {dmn}_datamodel::*;')
    elif stop_condition:
        rust_body.append(f'mod {stop_condition.lower()}_datamodel;')
        rust_body.append(f'use {stop_condition.lower()}_datamodel::*;')

    if stop_condition:
        rust_body.append(f'mod {stop_condition.lower()};')
        rust_body.append(f'use {stop_condition.lower()}::*;')

    rust_body.append('')

    # Context declarations at module level
    if not instance:
        rust_body.extend(context_decl)

    # ── Random generator declarations ──
    for each in process.random_generator:
        rust_body.extend([
            f'fn gen_{each}_init() -> u32 {{ rand::random::<u32>() % {each} + 1 }}'])

    # ── CREATE symbol support ──
    if not instance and process.dependencies['create']:
        for each in process.dependencies['create']:
            rust_body.extend([
                f'extern "C" {{ fn {each.lower()}_create_instance(from: {ASN1SCC}PID) -> {ASN1SCC}PID; }}'])

    # ── Get_State function ──
    if not generic and not instance and not stop_condition and not NO_CONTEXT:
        rust_body.extend([
            f'#[no_mangle]',
            f'pub unsafe extern "C" fn {process.name.lower()}_state() -> *const u8 {{',
            f'    // Return state as C string - simplified',
            f'    std::ptr::null()',
            f'}}',
            ''])

    # ── Startup declaration ──
    if not generic:
        rust_body.extend([
            f'#[no_mangle]',
            f'pub unsafe extern "C" fn {process.name.lower()}_startup() {{',
            f'    startup();',
            f'}}',
            ''])

    # ── Inner procedures ──
    inner_procedures_code = []
    for proc in process.content.inner_procedures:
        not_local = False
        spelling = proc.inputString
        for p_decl in process.procedures:
            if p_decl.inputString.lower() == proc.inputString.lower() \
                    and p_decl.referenced:
                spelling = p_decl.inputString
                not_local = True
        proc_code, proc_local = generate(proc, is_rpc=not_local)
        process_level_decl.extend(proc_local)
        inner_procedures_code.extend(proc_code)
        if proc.exported:
            spelling = proc.inputString
            for p_decl in process.procedures:
                if p_decl.inputString.lower() == proc.inputString.lower() \
                        and p_decl.referenced:
                    spelling = p_decl.inputString
                    not_local = True
            if not proc.external and not generic:
                if not_local:
                    rust_body.append(
                        f'#[no_mangle] pub extern "C" fn '
                        f'{process.name.lower()}_PI_{spelling}() {{ '
                        f'{proc.inputString}(); }}')
                else:
                    rust_body.append(
                        f'#[no_mangle] pub extern "C" fn {spelling}() {{ '
                        f'{proc.inputString}(); }}')

    rust_body.extend(process_level_decl)

    # ── Observer state status ──
    if process.errorstates or process.ignorestates or process.successstates:
        obs = ['unsafe fn observer_state_status() -> asn1SccObserver_State_Kind {']
        obs.append(f'    match {LPREFIX}.state {{')
        if process.errorstates:
            for st in process.errorstates:
                obs.append(f'        {generate_state_name(st)} => {ASN1SCC}Error_State,')
        if process.ignorestates:
            for st in process.ignorestates:
                obs.append(f'        {generate_state_name(st)} => {ASN1SCC}Ignore_State,')
        if process.successstates:
            for st in process.successstates:
                obs.append(f'        {generate_state_name(st)} => {ASN1SCC}Success_State,')
        obs.append(f'        _ => {ASN1SCC}Regular_State,')
        obs.append('    }')
        obs.append('}')
        obs.append('')
        rust_body.extend(obs)

    rust_body.extend(inner_procedures_code)
    rust_body.extend(aggreg_start_proc)

    # ── Labels ──
    Helper.add_labels_before_each_branch(process)
    Helper.inner_labels_to_floating(process)

    # ── PI generation ──
    generated_pis = set()
    for signal in process.input_signals + [
                        {'name': timer} for timer in process.timers]:
        if stop_condition:
            break

        if 'renames' in signal and signal['renames'] is not None:
            continue

        signame = signal.get('name', 'START')
        if signame.lower() in generated_pis:
            continue
        generated_pis.add(signame.lower())
        fake_name = False

        ignore_export = False
        proc_to_declare = None
        for proc in process.procedures:
            if proc.inputString.lower() == signame.lower():
                ignore_export = True
                proc_to_declare = proc
                break

        if ignore_export:
            fake_name = f'{signame}_Transition'
            has_transition = any(signame.lower() == k.lower()
                                 for k in process.input_mapping.keys()) or has_cs
            if not has_transition and not instance:
                continue

        if signame == 'START':
            continue

        # PI parameter
        param_name = signal.get('param_name') or f'{signame}_param'
        param_decl = ''
        if 'type' in signal:
            typename = type_name(signal['type'])
            param_decl = f'{param_name}: &mut {typename}'

        pi_name = fake_name or signame

        # PI body
        rust_body.append(f'// Provided interface "{signame}"')

        if (not generic and not ignore_export) or (ignore_export and instance):
            # Export as C function
            export_name = f'{process.name.lower()}_PI_{signame}'
            sig = f'pub unsafe extern "C" fn {signame}({param_decl})'
            if param_decl:
                sig = f'pub unsafe extern "C" fn {signame}({param_decl})'
            rust_body.append(f'#[no_mangle]')
            rust_body.append(sig + ' {')
        else:
            if param_decl:
                rust_body.append(f'unsafe fn {pi_name}({param_decl}) {{')
            else:
                rust_body.append(f'unsafe fn {pi_name}() {{')

        has_transition = any(signame.lower() == k.lower()
                             for k in process.input_mapping.keys())

        if not instance:
            if has_transition and not getattr(process, 'no_context', False):
                rust_body.append(f'    match {LPREFIX}.state {{')

            def execute_transition(state, dest, simu_step=False):
                input_defs = process.input_mapping[signame].get(state)
                if not input_defs:
                    return False
                state_tree = state.split(SEPARATOR)
                context = process
                exitlist = []
                current = ''
                first_input_def = input_defs[0]
                trans = first_input_def and process.transitions[
                    first_input_def.transition_id]
                while state_tree:
                    current = current + state_tree.pop(0)
                    for comp in context.composite_states:
                        if current.lower() == comp.statename.lower():
                            if comp.exit_procedure:
                                exitlist.append(current)
                            context = comp
                            current = current + SEPARATOR
                            break
                for each in reversed(exitlist):
                    if trans and all(each.startswith(trans_st)
                                    for trans_st in trans.possible_states):
                        dest.append(f'p{SEPARATOR}{each}{SEPARATOR}exit();')

                if first_input_def:
                    for inp in first_input_def.parameters:
                        dest.append(f'{LPREFIX}.{inp} = *{param_name};')

                    if len(input_defs) == 1:
                        if first_input_def.transition:
                            if simu_step:
                                dest.append(
                                    f'return Branches::{first_input_def.branch_label};')
                            else:
                                dest.append(
                                    f'execute_transition(Branches::{first_input_def.branch_label});')
                        else:
                            return False
                    else:
                        dest.append(
                            f'match {LPREFIX}.state_instance {{')
                        for inp_def in input_defs:
                            inst_name = inp_def.transition.possible_states[0]
                            dest.append(
                                f'{generate_state_name(inst_name)} =>')
                            if inp_def.transition:
                                dest.append(
                                    f'execute_transition(Branches::{inp_def.branch_label});')
                        dest.append('_ => execute_transition(Branches::Continuous_Signals);')
                        dest.append('}')
                else:
                    return False
                return True

            def case_state(state, dest, simu_step=False):
                if state.endswith('START'):
                    return
                statecase = [f'{generate_state_name(state)} => {{']
                input_def = process.input_mapping[signame].get(state)
                if state in process.aggregates.keys():
                    dest.extend(statecase)
                    dest.append('// State aggregation')
                    for sub in process.aggregates[state]:
                        if [a for a in sub.mapping.keys()
                                if a in process.input_mapping[signame].keys()]:
                            dest.append(
                                f'match {LPREFIX}.{sub.statename}{SEPARATOR}state {{')
                            for par in sub.mapping.keys():
                                case_state(par, dest, simu_step)
                            dest.append(
                                '_ => execute_transition(Branches::Continuous_Signals);')
                            if simu:
                                dest.append('panic!("Lost_Input");')
                            dest.append('}')
                            break
                    else:
                        if input_def:
                            execute_transition(state, dest, simu_step)
                        else:
                            dest.append(
                                'execute_transition(Branches::Continuous_Signals);')
                            if simu:
                                dest.append('panic!("Lost_Input");')
                    # Close the match arm
                    dest.append('}')
                else:
                    if execute_transition(state, statecase, simu_step):
                        dest.extend(statecase)
                        # Close the match arm
                        dest.append('}')

            if has_transition and not getattr(process, 'no_context', False):
                for each_state in reduced_statelist:
                    case_state(each_state, rust_body, False)
                rust_body.append('_ => {')
                rust_body.append('execute_transition(Branches::Continuous_Signals);')
                if simu and fake_name is False:
                    rust_body.append('panic!("Lost_Input");')
                rust_body.append('}')
                rust_body.append('}')
            elif has_cs:
                rust_body.append('execute_transition(Branches::Continuous_Signals);')
            else:
                rust_body.append('// no transition')

            if simu and fake_name is False:
                simu_code = []
                simu_code.append(
                    f'fn simu_{signame}({param_decl}) -> Branches {{')
                if has_transition and not getattr(process, 'no_context', False):
                    simu_code.append(f'match {LPREFIX}.state {{')
                    for each_state in reduced_statelist:
                        case_state(each_state, simu_code, True)
                    simu_code.append('_ => return Branches::Continuous_Signals;')
                    simu_code.append('}')
                elif has_cs:
                    simu_code.append('return Branches::Continuous_Signals;')
                else:
                    simu_code.append('return Branches::Branch_End;')
                simu_code.append('}')
                simu_code.append('')
                simu_pi_decl.append(simu_code)

        elif not fake_name or instance:
            inst_call = f'{process.name}_Instance::{signame}'
            if 'type' in signal:
                inst_call += f'({param_name})'
            elif proc_to_declare and proc_to_declare.fpar:
                params = [p['name'] for p in proc_to_declare.fpar]
                inst_call += f'({", ".join(params)})'
            rust_body.append(f'{inst_call};')

        rust_body.append('}')
        rust_body.append('')

        if simu_pi_decl:
            for sc in simu_pi_decl:
                rust_body.extend(sc)

    # ── Continuous signals ──
    if has_cs:
        if not instance:
            cs_template = generate_code_for_continuous_signals(process, generic)
            rust_body.extend(cs_template)
        if not MONITORS and not generic:
            rust_body.extend([
                f'#[no_mangle]',
                f'pub unsafe extern "C" fn {process.name.lower()}_check_queue(res: &mut bool) {{',
                f'    // Provided by runtime',
                f'}}',
                ''])

    # ── Instance startup ──
    if instance:
        rust_body.extend([
            'unsafe fn startup() {',
            f'{process.name}_Instance::startup();',
            '}',
            ''])

    # ── RI declarations ──
    for signal in process.output_signals:
        sig = signal['name']
        param_name = signal.get('param_name') or f'{sig}_param'
        param_spec = ''
        if 'type' in signal:
            typename = type_name(signal['type'])
            if 'PID' in TYPES:
                param_spec = f'({param_name}: &mut {typename}, dest_pid: {ASN1SCC}PID)'
            else:
                param_spec = f'({param_name}: &mut {typename})'
        else:
            if 'PID' in TYPES:
                param_spec = f'(dest_pid: {ASN1SCC}PID)'

        if not generic and not instance:
            ri_stub_code.append(f'fn ri{SEPARATOR}{sig}{param_spec} {{ /* RI stub - implement me */ }}')

    # ── External procedure RIs ──
    for proc in (proc for proc in process.procedures if proc.external):
        sig = proc.inputString
        params = []
        for param in proc.fpar:
            typename = type_name(param['type'])
            params.append(f'{param["name"]}: &mut {typename}')
        params_spec = f'({", ".join(params)})' if params else '()'
        if not generic and not instance:
            ri_stub_code.append(f'fn ri{SEPARATOR}{sig}{params_spec} {{ /* RI stub */ }}')

    # ── Timer declarations ──
    for timer in process.timers:
        if stop_condition:
            break
        if not generic:
            ri_stub_code.append(
                f'fn set_{timer}(val: &mut {ASN1SCC}T_UInt32) {{ /* timer stub */ }}')
            ri_stub_code.append(f'fn reset_{timer}() {{ /* timer stub */ }}')

    # ── Branches enum ──
    all_labels = [lab.inputString for lab in process.content.floating_labels]
    if not instance and not NO_CONTEXT:
        branches = ', '.join(all_labels + ['Continuous_Signals', 'Branch_End'])
        rust_body.append(f'#[derive(Clone, Copy, PartialEq, Debug)]')
        rust_body.append(f'enum Branches {{ {branches} }}')
        rust_body.append('')

        if simu:
            rust_body.append('static mut BRANCH_COVERAGE: [bool; 256] = [false; 256];')

    # ── Transition code ──
    code_transitions = []
    local_decl_transitions = []
    for proc_tr in process.transitions:
        code_tr, tr_local_decl = generate(proc_tr)
        code_transitions.append(code_tr)
        local_decl_transitions.extend(tr_local_decl)

    # ── Floating labels as functions ──
    code_labels = []
    for label in process.content.floating_labels:
        if NO_CONTEXT:
            break
        # _floating_label generates the complete function (signature + body + closing brace)
        # so we just extend with its output
        code_label, _ = generate(label)
        rust_body.extend(code_label)

    # ── Execute_Transition and Execute_Branch_Loop ──
    if process.transitions and not instance and not NO_CONTEXT:
        if simu:
            rust_body.extend([
                f'#[no_mangle]',
                f'pub unsafe extern "C" fn {process.name.lower()}_simu_next(branch: Branches) -> Branches {{',
                '    let mut next_branch = branch;',
                '    match next_branch {'])
            for label in all_labels:
                rust_body.append(
                    f'        Branches::{label} => {{ BRANCH_COVERAGE[{list(all_labels).index(label)}] = true; '
                    f'next_branch = branch_{label}(); }}')
            if has_cs:
                rust_body.append(
                    '        Branches::Continuous_Signals => next_branch = branch_continuous_signals(),')
            else:
                rust_body.append(
                    '        Branches::Continuous_Signals => next_branch = Branches::Branch_End,')
            rust_body.append('        Branches::Branch_End => {}')
            rust_body.append('    }')
            rust_body.append('    next_branch')
            rust_body.append('}')
            rust_body.append('')

        # Declare local variables from transitions
        for decl in set(local_decl_transitions):
            rust_body.append(decl)

        rust_body.extend([
            'unsafe fn execute_branch_loop(branch: Branches) {',
            '    let mut next_branch = branch;',
            '    while next_branch != Branches::Branch_End {',
            '        match next_branch {'])
        for label in all_labels:
            rust_body.append(
                f'            Branches::{label} => next_branch = branch_{label}(),')
        if has_cs:
            rust_body.append(
                '            Branches::Continuous_Signals => next_branch = branch_continuous_signals(),')
        else:
            rust_body.append(
                '            Branches::Continuous_Signals => next_branch = Branches::Branch_End,')
        rust_body.append('            Branches::Branch_End => {}')
        rust_body.append('        }')
        rust_body.append('    }')
        rust_body.append('}')
        rust_body.append('')

        rust_body.extend([
            'unsafe fn execute_transition(branch: Branches) {',
            f'    if !{LPREFIX}.init_done && branch != Branches::Startup_Transition {{',
            '        return;',
            '    }',
            '    execute_branch_loop(branch);',
            '}',
            ''])

        rust_body.extend(code_labels)

    elif not instance and not NO_CONTEXT:
        rust_body.extend([
            'unsafe fn execute_transition(branch: Branches) {}',
            ''])

    # ── Startup ──
    rust_body.extend(start_transition)

    # ── RI stubs ──
    if not taste and ri_stub_code:
        rust_body.append('// RI stubs - implement these in your code')
        rust_body.extend(ri_stub_code)

    # ── Cargo.toml ──
    # This Cargo.toml is written to <process>_cargo.toml.
    # The test Makefile should copy it to Cargo.toml (overwriting asn1scc's version).
    cargo_toml = f'''[package]
name = "{process.name.lower()}"
version = "0.1.0"
edition = "2021"

[dependencies]
asn1rust = {{ path = "asn1rust" }}

[lib]
name = "{process.name.lower()}"
path = "{process.name.lower()}.rs"

[[bin]]
name = "test_rust"
path = "main.rs"

[profile.release]
opt-level = 3
'''

    # ── Write files ──
    with open(process.name.lower() + os.extsep + 'rs', 'w') as rust_file:
        rust_file.write('\n'.join(format_rust_code(rust_body)))

    # Post-process: add 'use crate::dataview_uniq::*;' to the asn1scc-generated
    # datamodel file so it can access dataview functions (IsConstraintValid, init, etc.)
    dmn = process.name.lower()
    dmn_rs = f'{dmn}_datamodel.rs'
    if os.path.exists(dmn_rs):
        with open(dmn_rs, 'r') as f:
            content = f.read()
        if 'use crate::dataview_uniq::' not in content:
            # Insert after the last 'use' line
            lines = content.split('\n')
            insert_idx = 0
            for i, line in enumerate(lines):
                if line.startswith('use '):
                    insert_idx = i + 1
            lines.insert(insert_idx, 'use crate::dataview_uniq::*;')
            with open(dmn_rs, 'w') as f:
                f.write('\n'.join(lines))

    if not taste:
        ri_stub_file = f'{process.name.lower()}_ri.rs'
        if not os.path.exists(ri_stub_file) and ri_stub_code:
            with open(ri_stub_file, 'w') as ri_stub:
                ri_stub.write('\n'.join(format_rust_code([
                    f'// RI stubs for {process.name} - implement these functions',
                    f'#![allow(non_snake_case)]'] + ri_stub_code)))

    with open(f'{process.name.lower()}_cargo.toml', 'w') as cargo:
        cargo.write(cargo_toml)

    # ── Generate instance if needed ──
    if process_instance is not process:
        process_instance.timers = process.timers
        process_instance.cs_mapping = process.cs_mapping
        generate(process_instance, simu, instance=True, taste=taste)


def write_statement(param, newline):
    '''Generate the code for the special "write" operator (Rust)'''
    code = []
    local = []
    basic_type = find_basic_type(param.exprType) or {}
    type_kind = basic_type.kind
    if isinstance(param, ogAST.ExprAppend):
        st1, _, lcl1 = write_statement(param.left, newline=False)
        st2, _, lcl2 = write_statement(param.right, newline=False)
        code.extend(st1)
        code.extend(st2)
        local.extend(lcl1)
        local.extend(lcl2)
    elif type_kind == 'IA5StringType':
        code, string, local = expression(param, readonly=1)
        code.append(f'print!("{{}}", String::from_utf8_lossy(&{string}));')
    elif type_kind.endswith('StringType'):
        if isinstance(param, ogAST.PrimOctetStringLiteral):
            code.append(f'print!("{param.printable_string}");')
        elif isinstance(param, ogAST.PrimStringLiteral):
            code.append(f'print!("{param.value[1:-1]}");')
        else:
            code, string, local = expression(param, readonly=1)
            code.append(f'print!("{{:?}}", {string});')
    elif type_kind in ('IntegerType', 'Integer32Type', 'IntegerU8Type'):
        code, string, local = expression(param, readonly=1)
        code.append(f'print!("{{}}", {string});')
    elif type_kind == 'RealType':
        code, string, local = expression(param, readonly=1)
        code.append(f'print!("{{}}", {string});')
    elif type_kind == 'BooleanType':
        code, string, local = expression(param, readonly=1)
        code.append(f'print!("{{}}", if {string} {{ "true" }} else {{ "false" }});')
    else:
        code, string, local = expression(param, readonly=1)
        code.append(f'print!("{{:?}}", {string});')
    if newline:
        code.append('println!();')
    return code, '', local


